"""Parameter adapter for concept A (the ONLY module that knows concept A's file layout).

The design loop (cli.py) talks to a design through this small interface:

    ADAPTER_NAME                       str
    list_parameters()                  -> {name: description}
    parse_changes(["name=value", ...]) -> opaque change list
    stage(repo_root, work_root)        copy the design files the checks need into work_root
    run_checks(work_root, changes)     -> {"steps": [...], "metrics": {...}, "changes": [...]}
    KEY_METRICS                        ids shown first in the report

When the team's shared aircraft schema (T-034) exists, write adapter_<schema>.py with the same names and pass
`--adapter adapter_<schema>` to cli.py; cli.py itself does not change. Nothing here edits the committed design.

Concept A today = redesign/qp/A (params-A.json is generated by proofs/gen_params_a.py from the CAD mass table etc.;
the claims in proofs/claims_a*.py read params-A.json; redesign/interfaces/merge_check.py rolls up the part masses).
Order of one check run, all inside the copy: gen_params_a -> apply changes -> merge_check (mass/CG roll-up, fed to
mass.basic_cad_kg and mass.cg_x_mm as deltas) -> claims_a0..a3 -> build_graph (--strict; its exit code is recorded, a failing
claim is a result, not a crash). Stdlib only.
"""
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

ADAPTER_NAME = "concept_a"
SKIP_DIRS = {"__pycache__", "runs", "shots", "frames", "renders", "node_modules", "viewer"}
MAX_FILE_BYTES = 300_000          # large renders/meshes are not read by the fast checks (same 16 failing claims as with 2 MB)
PY = [sys.executable, "-I"]

RB = "rigid-body (static mass properties, algebra)"
FD = "flight dynamics (algebraic, EST inputs)"
FEA = "FEA / hand calc (stored result read, not re-run)"
INT = "interference (stored gate result, not re-run)"
SITL = "rigid-body dynamics (stored SITL result read, not re-run)"
CATEGORY = [  # first matching prefix wins
    ("CL-A-MASS", RB), ("CL-A-CUTS", RB), ("CL-A-CG", RB), ("CL-A-STRUCT-MASS", RB),
    ("CL-A-SM", FD), ("CL-A-TW", FD), ("CL-A-WINDOW", FD), ("CL-A-MOTOR", FD), ("CL-A-ESC", FD), ("CL-A-CRUISE", FD),
    ("CL-A-FENCE", FD), ("CL-A-STALL", FD), ("CL-A-YAW", FD), ("CL-A-PITCH", FD), ("CL-A-SERVO", FD),
    ("CL-A-COST", "illustrative (budget arithmetic)"), ("CL-A-SCHED", "illustrative (schedule arithmetic)"),
    ("CL-A-COLL", INT), ("CL-A-WIRE", INT), ("CL-A-ASSY", INT), ("CL-A-BOX", INT),
    ("CL-A-MS-", FEA), ("CL-A-FOAM", FEA), ("CL-A-FLUTTER", FEA), ("CL-A-VIB", FEA), ("CL-A-HORN", FEA), ("CL-A-BRIDGE", FEA),
    ("CL-A-DIVERGENCE", FEA), ("CL-A-REVERSAL", FEA), ("CL-A-GUST", FEA), ("CL-A-LANDING", FEA),
    ("CL-A-WIND", SITL), ("CL-A-ROLL", SITL), ("CL-A-TIPOVER", SITL),
]
KEY_METRICS = ["MC-MASS-TOTAL", "MC-CG-X", "CL-A-MASS-PRED", "CL-A-CG", "CL-A-CG-HI", "CL-A-SM", "CL-A-TW-FRESH-PRED",
               "CL-A-TW-SAG-PRED", "CL-A-WINDOW-PRED", "CL-A-MOTOR-I", "CL-A-ESC-I", "CL-A-CRUISE-NEED", "CL-A-CRUISE-AVAIL",
               "CL-A-COST-TOTAL"]

PARAMETERS = {
    "pack_capacity_ah": "Pack capacity in Ah (baseline 2.8). Sets mission.pack_ah; pack mass scaled linearly at the baseline g/Ah "
                        "(EST: no vendor listing for the new size; pack size and CG offset not re-modelled) in mass.pack_g, the "
                        "itemised pack row and PWR-001; the mass/CG roll-up then feeds mass.basic_cad_kg and mass.cg_x_mm.",
    "part_mass:<ID>": "Mass in g of one CAD part by interfaces id, e.g. part_mass:PWR-001=285. The roll-up updates basic mass and CG "
                      "(the itemised cross-check CL-A-MASS-ITEM is not updated for parts other than the pack).",
    "param:<group.name>": "Any params-A.json value by dotted path, e.g. param:mission.cruise_ms=18. Written verbatim (no coupling), "
                          "after gen_params_a, so it overrides the generated value.",
}


def list_parameters():
    return dict(PARAMETERS)


def category_of(claim_id):
    for pre, cat in CATEGORY:
        if claim_id.startswith(pre):
            return cat
    return "illustrative (uncategorised claim)"


def parse_changes(items):
    """['pack_capacity_ah=3.3', 'part_mass:PWR-001=285', 'param:mission.cruise_ms=18'] -> [(kind, key, float)]"""
    out = []
    for s in items:
        if "=" not in s:
            raise ValueError(f"change '{s}' must be name=value")
        k, v = s.rsplit("=", 1)
        v = float(v)
        if k == "pack_capacity_ah":
            out.append(("pack_capacity_ah", None, v))
        elif k.startswith("part_mass:"):
            out.append(("part_mass", k.split(":", 1)[1], v))
        elif k.startswith("param:"):
            out.append(("param", k.split(":", 1)[1], v))
        else:
            raise ValueError(f"unknown parameter '{k}'; see `cli.py list-params`")
    return out


# ------------------------------------------------------------------ staging
def stage(repo_root, work_root):
    repo_root, work_root = Path(repo_root), Path(work_root)
    n = 0
    for sub in ("proofs", "interfaces", "qp/A"):
        for r, ds, fs in os.walk(repo_root / "redesign" / sub):
            ds[:] = [d for d in ds if d not in SKIP_DIRS]
            for f in fs:
                p = Path(r) / f
                if p.stat().st_size > MAX_FILE_BYTES:
                    continue
                q = work_root / p.relative_to(repo_root)
                q.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(p, q)
                n += 1
    return n


# ------------------------------------------------------------------ helpers
def _run(cmd, cwd, label):
    t = time.time()
    r = subprocess.run(PY + cmd, cwd=cwd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    return {"step": label, "cmd": "python -I " + " ".join(cmd), "exit": r.returncode, "wall_s": round(time.time() - t, 2),
            "tail": (r.stdout + r.stderr).strip().splitlines()[-4:]}


def _model(work):
    return Path(work) / "redesign" / "qp" / "A" / "cad" / "model"


def _interfaces(work):
    return sorted(_model(work).glob("*/interfaces.json"))


def _rollup(work):
    """Mass (g) and CG (x, y in mm) over every part with mass_g and cg_xyz_m in the staged interfaces files."""
    m = mx = my = 0.0
    for f in _interfaces(work):
        for p in json.loads(f.read_text(encoding="utf-8"))["parts"]:
            if p.get("mass_g") is None or not p.get("cg_xyz_m"):
                continue
            m += p["mass_g"]
            mx += p["mass_g"] * p["cg_xyz_m"][0]
            my += p["mass_g"] * p["cg_xyz_m"][1]
    return {"mass_g": m, "cg_x_mm": mx / m * 1000, "cg_y_mm": my / m * 1000}


def _set_part_mass(work, pid, grams):
    for f in _interfaces(work):
        d = json.loads(f.read_text(encoding="utf-8"))
        for p in d["parts"]:
            if p["id"] == pid:
                old = p["mass_g"]
                p["mass_g"] = grams
                f.write_text(json.dumps(d, indent=1), encoding="utf-8")
                return old
    raise KeyError(f"no part id {pid} in the concept A interfaces files")


def _params_path(work):
    return Path(work) / "redesign" / "qp" / "A" / "params-A.json"


def _node(P, dotted):
    node = P
    for k in dotted.split("."):
        if not isinstance(node, dict) or k not in node:
            raise KeyError(f"params-A.json has no entry {dotted}")
        node = node[k]
    if "value" not in node:
        raise KeyError(f"params-A.json entry {dotted} has no value")
    return node


# ------------------------------------------------------------------ changes (in the copy only)
def apply_changes(work, changes):
    """Apply parsed changes to the staged copy (after gen_params_a). Mass changes go through the interfaces files; the
    roll-up delta is then added to params-A.json. Returns records [{change, old, new, unit, note}]."""
    P = json.loads(_params_path(work).read_text(encoding="utf-8"))
    base = _rollup(work)
    recs, mass_touched = [], False
    for kind, key, val in changes:
        if kind == "pack_capacity_ah":
            ah, gm = _node(P, "mission.pack_ah"), _node(P, "mass.pack_g")
            old_ah, old_g = ah["value"], gm["value"]
            new_g = round(old_g * val / old_ah, 2)
            ah["value"], gm["value"] = val, new_g
            row = next(r for r in _node(P, "mass.itemised_g_growth")["value"] if r[0] == old_g and r[1] == 0.0)
            row[0] = new_g
            _set_part_mass(work, "PWR-001", new_g)
            mass_touched = True
            recs.append({"change": "pack_capacity_ah", "old": old_ah, "new": val, "unit": "Ah",
                         "note": f"pack mass {old_g} -> {new_g} g (linear in Ah, EST); PWR-001, mass.pack_g and the itemised pack row updated; BOM price and pack size NOT updated"})
        elif kind == "part_mass":
            old = _set_part_mass(work, key, val)
            mass_touched = True
            recs.append({"change": f"part_mass:{key}", "old": old, "new": val, "unit": "g", "note": "interfaces.json part mass_g"})
        else:
            n = _node(P, key)
            old, n["value"] = n["value"], val
            recs.append({"change": f"param:{key}", "old": old, "new": val, "unit": n.get("unit", ""), "note": "params-A.json value, verbatim"})
    if mass_touched:
        new = _rollup(work)
        _node(P, "mass.basic_cad_kg")["value"] += (new["mass_g"] - base["mass_g"]) / 1000
        _node(P, "mass.cg_x_mm")["value"] += new["cg_x_mm"] - base["cg_x_mm"]
        recs.append({"change": "mass roll-up", "old": round(base["mass_g"], 2), "new": round(new["mass_g"], 2), "unit": "g",
                     "note": f"CG x {base['cg_x_mm']:.3f} -> {new['cg_x_mm']:.3f} mm (lateral CG not updated); deltas added to mass.basic_cad_kg, mass.cg_x_mm"})
    _params_path(work).write_text(json.dumps(P, indent=1), encoding="utf-8")
    return recs


# ------------------------------------------------------------------ the checks
def run_checks(work, changes=None):
    """gen_params -> (changes) -> merge_check -> claims -> build_graph. Returns steps, metrics and applied-change records."""
    work = Path(work)
    A = work / "redesign" / "qp" / "A"
    steps, recs = [], []
    steps.append(_run([str(A / "proofs" / "gen_params_a.py")], work, "gen_params_a"))
    if steps[-1]["exit"]:
        return {"steps": steps, "metrics": {}, "changes": recs}
    if changes:
        recs = apply_changes(work, changes)
    steps.append(_run([str(work / "redesign" / "interfaces" / "merge_check.py"), "--root", str(_model(work)), "--out", str(work / "mc_out"),
                       "--budget", str(_model(work) / "mass_budget.json")], work, "merge_check"))
    for s in ("claims_a0_base", "claims_a1_flight", "claims_a2_struct", "claims_a3_program"):
        steps.append(_run([str(A / "proofs" / f"{s}.py")], work, s))
        if steps[-1]["exit"]:
            return {"steps": steps, "metrics": {}, "changes": recs}
    steps.append(_run([str(work / "redesign" / "proofs" / "build_graph.py"), "--root", str(A), "--out", str(A / "proofs" / "out"),
                       "--dataset", "concept-a", "--strict"], work, "build_graph --strict"))
    metrics = read_claims(A / "proofs" / "out" / "graph.json")
    metrics.update(read_merge(work, steps))
    return {"steps": steps, "metrics": metrics, "changes": recs}


def read_merge(work, steps):
    roll = _rollup(work)
    b = json.loads((_model(work) / "mass_budget.json").read_text(encoding="utf-8"))
    lim_g, (lo, hi) = b["limit_g"], [x * 1000 for x in b["cg_x_m"]]
    mc = next(s for s in steps if s["step"] == "merge_check")
    return {
        "MC-MASS-TOTAL": {"title": "merge_check CAD mass roll-up vs budget limit", "value": round(roll["mass_g"], 2), "unit": "g",
                          "limit": f"<= {lim_g}", "pass": roll["mass_g"] <= lim_g, "margin": (lim_g - roll["mass_g"]) / lim_g, "category": RB},
        "MC-CG-X": {"title": "merge_check CG aft of LE vs budget band", "value": round(roll["cg_x_mm"], 3), "unit": "mm", "limit": f"{lo:.1f} .. {hi:.1f}",
                    "pass": lo <= roll["cg_x_mm"] <= hi, "margin": None, "category": RB},
        "MC-GRAPH": {"title": "merge_check interface graph (exit code; its only error today is the mass limit above)", "value": mc["exit"],
                     "unit": "exit code", "limit": "0", "pass": mc["exit"] == 0, "margin": None, "category": "interference (graph consistency, static)"},
    }


def read_claims(graph_json):
    g = json.loads(Path(graph_json).read_text(encoding="utf-8"))
    out = {}
    for n in g["nodes"]:
        if n["type"] != "claim":
            continue
        lim, v = n.get("limit"), n.get("value")
        numeric = isinstance(v, (int, float)) and not isinstance(v, bool)
        out[n["id"]] = {"title": n["title"], "value": v, "unit": n.get("unit"),
                        "limit": f"{lim['op']} {lim.get('resolved')}" if lim else "-",
                        "pass": (not n.get("fails")) if (lim and numeric) else None,   # no limit or value "-": not judged
                        "margin": n.get("margin"), "status": n.get("status"), "category": category_of(n["id"])}
    return out
