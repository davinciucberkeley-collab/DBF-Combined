"""T-037 Part 4: upload <part id>.step files to API Test / branch concept-a-snapshot-73656c93 under package "CAD geometry".
Usage: python -I tools/davinci_step_upload.py <step dir> <viewer-data.json> <out record json>
(stdlib; token from .env, never printed; session grant never printed; no agent prompt; main never written; no commit here).
Idempotent: parts whose geometry (named <part id>) already sits in its subsystem sub-package are skipped.
Stops after two failures of the same kind."""
import json, os, sys, time, uuid, urllib.request, urllib.error
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import davinci_import_a as A

PID, BRANCH = A.PID, A.BRANCH


def upload_step(url, grant, name, fname, data):
    bd = "----dav" + uuid.uuid4().hex
    body = (f'--{bd}\r\nContent-Disposition: form-data; name="objectName"\r\n\r\n{name}\r\n'
            f'--{bd}\r\nContent-Disposition: form-data; name="file"; filename="{fname}"\r\n'
            f'Content-Type: application/step\r\n\r\n').encode() + data + f"\r\n--{bd}--\r\n".encode()
    req = urllib.request.Request(url, data=body, method="POST", headers={
        "Authorization": "Bearer " + grant, "Content-Type": "multipart/form-data; boundary=" + bd, "Accept": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=300) as r:
            return r.status, json.loads(r.read().decode() or "{}")
    except urllib.error.HTTPError as e:
        try:
            return e.code, json.loads(e.read().decode())
        except Exception:
            return e.code, {"raw": "unreadable"}


def tree():
    c, t = A.call("tree", "GET", f"/projects/{PID}/tree?branch={BRANCH}")
    objs = t.get("objects") or t.get("tree") or t.get("nodes") or []
    if isinstance(objs, dict):
        objs = [dict(v, id=i) for i, v in objs.items()]
    return objs


def open_session():
    c, ses = A.call("open_session", "POST", f"/projects/{PID}/sessions", {"branch": BRANCH, "ttlSeconds": 3600})
    sid = (ses or {}).get("sessionId") or (ses or {}).get("id")
    dp = (ses or {}).get("dataPlane") or {}
    owner = dp.get("ownerId") or ses.get("ownerId")
    base = (f"{dp['url'].rstrip('/')}/api/v1/file/upload/{owner}/{dp.get('userId') or owner}/"
            f"{dp.get('projectKey') or PID + '--' + BRANCH}/{dp.get('connectionId') or 'headless-' + sid}/")
    return sid, base, dp["token"]


def main():
    sd, vdp, out = sys.argv[1:4]
    A.KEY = A.load_key()
    assert A.KEY.startswith(("dav_ak_live_", "dav_ak_test_")), "no token"
    rec = {"usage_before": A.usage()}
    parts = json.load(open(vdp, encoding="utf-8"))["parts"]
    sub_of = {p["id"]: p["subsystem"] for p in parts}
    subs = sorted(set(sub_of.values()))
    ROOT = A.oid("cadgeo/root")
    SP = {s: A.oid("cadgeo/sub/" + s) for s in subs}
    files = sorted(f[:-5] for f in os.listdir(sd) if f.endswith(".step"))
    pk = {ROOT: dict(type="package", parent=A.MODEL, name="CAD geometry",
                     documentation="STEP geometry of every CAD part with geometry in concept-a.glb at 73656c93 (aircraft frame, mm). Faceted B-rep generated by tools/mesh_to_step.py from the GLB mesh (planar faces merged, curved regions as triangles): an approximation of the parametric parts, not the true solids. HRN-001 and HRD-001 are mass proxies with no geometry.")}
    for s in subs:
        pk[SP[s]] = dict(type="package", parent=ROOT, name=f"{s} geometry ({sum(1 for f in files if sub_of.get(f) == s)} parts)")
    if A.post("pkgs", pk)[0][0] != 201:
        print("package post failed")
        return 1
    rep = set(os.environ.get("REPLACE_PARTS", "").split(",")) - {""}
    if rep:  # delete the earlier geometry of a part whose STEP changed, then upload again
        for o in tree():
            if o.get("type") == "geometry" and o.get("parent") in SP.values() and o.get("name") in rep:
                A.call("delete_old", "DELETE", f"/projects/{PID}/objects/{o['id']}?branch={BRANCH}")
    have = {(o.get("parent"), o.get("name")) for o in tree() if o.get("type") == "geometry"}
    todo = [f for f in files if (SP[sub_of[f]], f) not in have]
    print("to upload", len(todo), "of", len(files))
    rec["uploads"] = {}
    fails, sid, t0 = [], None, 0
    try:
        for i, pid in enumerate(todo):
            if sid is None or time.time() - t0 > 2400:
                if sid:
                    A.call("close_session", "DELETE", f"/projects/{PID}/sessions/{sid}")
                sid, base, grant = open_session()
                t0 = time.time()
            data = open(os.path.join(sd, pid + ".step"), "rb").read()
            code, resp = upload_step(base + SP[sub_of[pid]], grant, pid, pid + ".step", data)
            rec["uploads"][pid] = {"http": code, "bytes": len(data)}
            if code != 200:
                rec["uploads"][pid]["resp"] = json.dumps(resp)[:400]
                fails.append((code, json.dumps(resp)[:120]))
                print("FAIL", pid, code, json.dumps(resp)[:300])
                if len(fails) >= 2 and fails[-1][0] == fails[-2][0]:
                    print("two failures of the same kind: stop")
                    break
            elif i % 10 == 0:
                print("uploaded", i + 1, "/", len(todo), flush=True)
    finally:
        if sid:
            A.call("close_session", "DELETE", f"/projects/{PID}/sessions/{sid}")
    objs = tree()
    geo = {}
    for o in objs:
        if o.get("type") == "geometry" and o.get("parent") in SP.values():
            geo.setdefault(o.get("name"), []).append(o.get("id"))
    rec["geometry_ids"] = geo
    rec["root"], rec["subs"] = ROOT, SP
    rec["geometries_in_tree"] = sum(len(v) for v in geo.values())
    rec["missing"] = [f for f in files if f not in geo]
    rec["duplicates"] = [k for k, v in geo.items() if len(v) > 1]
    print("geometries in tree", rec["geometries_in_tree"], "missing", rec["missing"], "dups", rec["duplicates"])
    rec["usage_after"] = A.usage()
    json.dump(rec, open(out, "w", encoding="utf-8"), indent=1)
    return 0


if __name__ == "__main__":
    sys.exit(main())
