"""contact_sheet.py - one PNG with every printed STL as the slicer will see it (bed = grey plane, Z up), and one PNG
preview of every laser/knife DXF nest. matplotlib only."""
import math
import os

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt                              # noqa: E402
import numpy as np                                           # noqa: E402
from mpl_toolkits.mplot3d.art3d import Poly3DCollection     # noqa: E402

import dxf                                                   # noqa: E402
import mesh_ops                                              # noqa: E402

LIGHT = np.array([0.35, -0.55, 0.76])
LIGHT = LIGHT / np.linalg.norm(LIGHT)
COL = {'PETG': (0.30, 0.55, 0.88), 'ASA': (0.88, 0.45, 0.20), 'TPU95A': (0.35, 0.70, 0.40)}
SWATCH = {'orange': (0.95, 0.55, 0.15), 'blue': (0.20, 0.40, 0.90), 'white': (0.92, 0.92, 0.92),
          'yellow': (0.95, 0.85, 0.20), 'green': (0.30, 0.75, 0.35)}


def render(items, path, cols=6):
    """items: [(stl path, title, material, colour)]."""
    n = len(items)
    rows = math.ceil(n / cols)
    fig = plt.figure(figsize=(cols * 3.1, rows * 3.3), dpi=110)
    for k, (p, title, mat, colour) in enumerate(items):
        ax = fig.add_subplot(rows, cols, k + 1, projection='3d')
        tris = mesh_ops.read_stl(p)
        base = np.array(SWATCH.get(colour, COL.get(mat, (0.6, 0.6, 0.6))))
        nrm = np.cross(tris[:, 1] - tris[:, 0], tris[:, 2] - tris[:, 0])
        ln = np.linalg.norm(nrm, axis=1)
        ln[ln == 0] = 1
        shade = 0.35 + 0.65 * np.clip((nrm / ln[:, None]) @ LIGHT, 0, 1)
        fc = np.clip(base[None, :] * shade[:, None], 0, 1)
        pc = Poly3DCollection(tris, facecolors=fc, edgecolors='none', linewidths=0)
        ax.add_collection3d(pc)
        lo, hi = tris.reshape(-1, 3).min(axis=0), tris.reshape(-1, 3).max(axis=0)
        span = max(hi - lo) * 0.55 + 1
        cx, cy = (lo[0] + hi[0]) / 2, (lo[1] + hi[1]) / 2
        bed = [[(cx - span, cy - span, 0), (cx + span, cy - span, 0), (cx + span, cy + span, 0), (cx - span, cy + span, 0)]]
        ax.add_collection3d(Poly3DCollection(bed, facecolors=(0.85, 0.85, 0.85, 0.5), edgecolors=(0.6, 0.6, 0.6)))
        ax.set_xlim(cx - span, cx + span)
        ax.set_ylim(cy - span, cy + span)
        ax.set_zlim(0, 2 * span)
        ax.set_box_aspect((1, 1, 1))
        ax.view_init(elev=24, azim=-58)
        ax.set_axis_off()
        d = hi - lo
        ax.set_title('%s\n%.1f x %.1f x %.1f mm' % (title, d[0], d[1], d[2]), fontsize=7)
    fig.suptitle('K09-L printed parts and jigs, as placed on the bed (Z up, grey = bed). Generated by '
                 'make_shop_files.py', fontsize=10)
    fig.tight_layout(rect=(0, 0, 1, 0.98))
    fig.savefig(path)
    plt.close(fig)


def dxf_preview(files, path):
    """files: [(dxf path, title, sheet w, sheet h)]."""
    n = len(files)
    cols = 3
    rows = math.ceil(n / cols)
    fig, axs = plt.subplots(rows, cols, figsize=(cols * 6, rows * 4.2), dpi=100, squeeze=False)
    for k, (p, title, w, h) in enumerate(files):
        ax = axs[k // cols][k % cols]
        polys, _t = dxf.read(p)
        for layer, closed, pts in polys:
            xs = [q[0] for q in pts] + ([pts[0][0]] if closed else [])
            ys = [q[1] for q in pts] + ([pts[0][1]] if closed else [])
            ax.plot(xs, ys, color={'CUT': 'r', 'MARK': 'b'}.get(layer, '0.6'), lw=0.5)
        ax.set_aspect('equal')
        ax.set_title(title, fontsize=8)
        ax.tick_params(labelsize=6)
    for k in range(n, rows * cols):
        axs[k // cols][k % cols].set_axis_off()
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)
