"""figures.py - plan, render (via the Blender toolkit) and post-process the manual's figures. Standard library only.

  plan(manual)            -> every figure spec (cover/overview figures from manual.json + one or more per step)
  stale(specs, img, fp)   -> the ids whose PNG is missing or whose spec/geometry changed since the last render
  render(...)             -> runs redesign/blender/render_figures.py once for all stale figures
  markers(sidecar, step)  -> numbered dots (action numbers) placed next to the anchors Blender found
  numbered_svg(...)       -> self-contained SVG (JPEG + numbered dots) for the Markdown manual

A figure's hash covers its spec plus every input that changes geometry or look (interfaces, params, modules, the
Blender toolkit and the design-system render style), so only what changed is re-rendered.
"""
import base64
import glob
import hashlib
import json
import math
import os
import shutil
import subprocess
import time

import steps_lib as L

BLENDER_DIR = os.path.join(L.REDESIGN, 'blender')
R, LEAD = 24, 92            # marker radius and leader length in render pixels (1600 px wide image)


def find_blender(explicit=None):
    """Blender executable: --blender, then env DBF_BLENDER, then PATH, then the usual install folders (any 4.x).
    Returns None when nothing is found; the caller prints what to set."""
    cands = [explicit, os.environ.get('DBF_BLENDER'), shutil.which('blender')]
    home = os.path.expanduser('~')
    for pat in (os.path.join(home, 'tools', 'blender', 'blender-4.*', 'blender.exe'),
                'C:/Program Files/Blender Foundation/Blender 4.*/blender.exe',
                '/Applications/Blender.app/Contents/MacOS/Blender',
                '/usr/bin/blender', '/snap/bin/blender'):
        cands += sorted(glob.glob(pat), reverse=True)       # newest 4.x first
    return next((c for c in cands if c and os.path.exists(c)), None)
HI, INK, PAPER = '#C2540A', '#121619', '#FFFFFF'


def plan(m):
    figs = []
    for f in m.meta.get('figures', []):
        f = dict(f)
        f.setdefault('scene', 'studio')
        figs.append(f)
    for s in m.steps:
        figs += s['figures']
    return figs


def fingerprint(m):
    """Hash of every file that changes what a render looks like."""
    pats = [os.path.join(d, '*', n) for d in {m.src, m.ifaces} for n in ('interfaces.json', 'params.json')]
    pats += [os.path.join(m.ifaces, '*', 'fusion', '*.py'), os.path.join(m.ifaces, 'modules.txt'),
             os.path.join(BLENDER_DIR, '*.py'), os.path.join(L.REDESIGN, 'design-system', 'blender-style.json'),
             os.path.join(L.REDESIGN, 'params', 'params.json'), os.path.join(L.REDESIGN, 'fusion', 'fusionkit.py')]
    h = hashlib.sha1()
    for p in sorted({f for pat in pats for f in glob.glob(pat)}):
        h.update(p.encode())
        with open(p, 'rb') as f:
            h.update(f.read())
    return h.hexdigest()


def fig_hash(spec, fp, quality):
    return hashlib.sha1((json.dumps(spec, sort_keys=True) + fp + json.dumps(quality)).encode()).hexdigest()[:16]


def read_lock(img):
    p = os.path.join(img, 'figures.lock.json')
    return L.load_json(p) if os.path.exists(p) else {}


def stale(specs, img, fp, quality, force=False):
    lock = read_lock(img)
    out = []
    for f in specs:
        have = os.path.exists(os.path.join(img, f['id'] + '.jpg')) and os.path.exists(os.path.join(img, f['id'] + '.json'))
        if force or not have or lock.get(f['id']) != fig_hash(f, fp, quality):
            out.append(f)
    return out


def render(specs, img, fp, quality, examples, root, blender=None, log=print):
    """One Blender run for all given figures. quality = {'samples': n, 'percent': p}. Returns (ok, seconds)."""
    if not specs:
        return True, 0.0
    blender = find_blender(blender)
    if not blender:
        log('Blender 4.x not found (not on PATH, no DBF_BLENDER env var, no --blender EXE); figures not rendered')
        return False, 0.0
    os.makedirs(img, exist_ok=True)
    spec_path = os.path.join(img, 'figures.spec.json')
    with open(spec_path, 'w', encoding='utf-8') as f:
        json.dump({'_note': 'generated by build_manual.py; edit steps.json, not this file', 'scene': 'workbench',
                   'figures': specs}, f, indent=1)
    cmd = [blender, '-b', '--factory-startup', '-P', os.path.join(BLENDER_DIR, 'render_figures.py'), '--',
           '--spec', spec_path, '--out', img, '--samples', str(quality['samples']), '--percent', str(quality['percent'])]
    cmd += ['--examples'] if examples else (['--root', root] if root else [])
    log('rendering %d figure(s): %s' % (len(specs), ', '.join(f['id'] for f in specs)))
    t0 = time.time()
    p = subprocess.run(cmd, capture_output=True, text=True, encoding='utf-8', errors='replace')
    for line in p.stdout.splitlines():
        if line.startswith(('rendered ', 'built in', 'all figures')) or 'CLIPPED' in line or 'Traceback' in line:
            log('  blender: ' + line.strip())
    lock = read_lock(img)
    ok = p.returncode == 0
    for f in specs:
        if os.path.exists(os.path.join(img, f['id'] + '.json')) and ok:
            lock[f['id']] = fig_hash(f, fp, quality)
        else:
            ok = False
    if not ok:
        log(p.stdout[-3000:] + p.stderr[-3000:])
    with open(os.path.join(img, 'figures.lock.json'), 'w', encoding='utf-8') as f:
        json.dump(lock, f, indent=1, sort_keys=True)
    return ok, time.time() - t0


def sidecar(img, fid):
    p = os.path.join(img, fid + '.json')
    return L.load_json(p) if os.path.exists(p) else None


def markers(sc, step):
    """Place one numbered dot per action that points at something ('at'). The dot sits a leader length away from the
    anchor, pointing away from the subject centre, and dots are pushed apart until none overlap.
    Returns ([{n, ax, ay, x, y, occluded}], [action numbers whose anchor is not in this figure])."""
    if not sc:
        return [], []
    W, H = sc['size']
    sx0, sy0, sx1, sy1 = sc.get('subject_px') or (0, 0, W, H)
    cx, cy = (sx0 + sx1) / 2, (sy0 + sy1) / 2
    co = sc.get('callouts', [])
    out, missing = [], []
    for n, a in enumerate(step['actions_n'], 1):
        at = a.get('at')
        if at is None:
            continue
        hit = None
        for c in co:
            if (isinstance(at, str) and c.get('item') == at) or \
                    (isinstance(at, list) and c.get('item') is None and
                     all(abs(u - v) < 1e-3 for u, v in zip(c.get('world_m', []), at))):
                hit = c
                break
        if hit is None:
            missing.append(n)
            continue
        ax, ay = hit['x'], hit['y']
        if not (0 <= ax <= W and 0 <= ay <= H):          # anchor outside this view (e.g. a detail figure)
            missing.append(n)
            continue
        dx, dy = ax - cx, ay - cy
        d = math.hypot(dx, dy) or 1.0
        dx, dy = (dx / d, dy / d) if d > 1 else (-0.7, -0.7)
        near = sum(1 for o in out if math.hypot(o['ax'] - ax, o['ay'] - ay) < 60)
        if near:                                         # anchors close together: fan the leaders out by angle
            t = math.radians(42 * ((near + 1) // 2) * (1 if near % 2 else -1))
            dx, dy = dx * math.cos(t) - dy * math.sin(t), dx * math.sin(t) + dy * math.cos(t)
        out.append({'n': n, 'ax': ax, 'ay': ay, 'x': ax + dx * LEAD, 'y': ay + dy * LEAD - 10, 'occluded': hit.get('occluded')})
    for _ in range(60):                                  # relax overlaps between dots
        moved = False
        for i in range(len(out)):
            for j in range(i + 1, len(out)):
                a, b = out[i], out[j]
                dx, dy = b['x'] - a['x'], b['y'] - a['y']
                d = math.hypot(dx, dy)
                if d < 2 * R + 10:
                    if d < 1e-3:
                        dx, dy, d = 1.0, 0.3, 1.04
                    push = (2 * R + 10 - d) / 2 + 0.5
                    a['x'] -= dx / d * push; a['y'] -= dy / d * push
                    b['x'] += dx / d * push; b['y'] += dy / d * push
                    moved = True
        for mk in out:
            mk['x'] = min(max(mk['x'], R + 6), W - R - 6)
            mk['y'] = min(max(mk['y'], R + 6), H - R - 6)
        if not moved:
            break
    for mk in out:
        for k in ('ax', 'ay', 'x', 'y'):
            mk[k] = round(mk[k], 1)
    return out, missing


def marker_svg(mks, scale=1.0, cls=True):
    """SVG fragment: halo + leader + anchor dot + numbered disc (design-system step card style)."""
    r = R * scale
    parts = []
    for m in mks:
        dash = ' stroke-dasharray="7 6"' if m.get('occluded') else ''
        g = '<g class="mk" data-n="%d">' % m['n'] if cls else '<g>'
        parts.append(g +
                     '<line x1="%s" y1="%s" x2="%s" y2="%s" stroke="%s" stroke-width="%s" stroke-linecap="round"/>'
                     % (m['ax'], m['ay'], m['x'], m['y'], PAPER, 7 * scale) +
                     '<line x1="%s" y1="%s" x2="%s" y2="%s" stroke="%s" stroke-width="%s"%s/>'
                     % (m['ax'], m['ay'], m['x'], m['y'], INK, 2.2 * scale, dash) +
                     '<circle cx="%s" cy="%s" r="%s" fill="%s" stroke="%s" stroke-width="%s"/>'
                     % (m['ax'], m['ay'], 6.5 * scale, PAPER if m.get('occluded') else HI, INK if m.get('occluded') else PAPER,
                        2.5 * scale) +
                     '<circle class="disc" cx="%s" cy="%s" r="%s" fill="%s" stroke="%s" stroke-width="%s"/>'
                     % (m['x'], m['y'], r, HI, PAPER, 3.5 * scale) +
                     '<text x="%s" y="%s" text-anchor="middle" dominant-baseline="central" font-family="IBM Plex Mono, '
                     'Consolas, monospace" font-weight="600" font-size="%s" fill="#fff">%d</text></g>'
                     % (m['x'], m['y'] + 1, 26 * scale, m['n']))
    return ''.join(parts)


def numbered_svg(img, fid, mks, caption=''):
    """Self-contained SVG (JPEG embedded) with the numbered dots: what the Markdown manual shows."""
    sc = sidecar(img, fid)
    jp = os.path.join(img, fid + '.jpg')
    if not sc or not os.path.exists(jp):
        return None
    W, H = sc['size']
    with open(jp, 'rb') as f:
        b64 = base64.b64encode(f.read()).decode()
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" width="%d" height="%d">'
           '<title>%s</title><image href="data:image/jpeg;base64,%s" width="%d" height="%d"/>%s</svg>'
           % (W, H, W, H, caption.replace('&', '&amp;').replace('<', '&lt;'), b64, W, H, marker_svg(mks, cls=False)))
    out = os.path.join(img, fid + '.numbered.svg')
    with open(out, 'w', encoding='utf-8') as f:
        f.write(svg)
    return out
