"""md_out.py - the Markdown manual (MANUAL.md, reads on GitHub) plus kitting.csv and tools.csv. Standard library only.

Same content as the HTML, in the design-system Markdown style: ids and statuses in backticks, tables over prose,
one H1. Step figures are self-contained SVGs (render + numbered dots), so they show on GitHub without the HTML.
"""
import csv
import os
import re

import steps_lib as L
from html_out import fmt_min, qty


def md_text(m, s):
    """Numbers from params, ids in backticks (outside existing `code`), table pipes escaped."""
    s = m.sub_params(s or '')
    parts = re.split(r'(`[^`]*`)', s)
    parts = [p if p.startswith('`') else L.ID_RE.sub(lambda mt: '`%s`' % mt.group(1), p) for p in parts]
    return ''.join(parts).replace('|', '\\|')


def cell(s):
    return str(s if s is not None else '—').replace('|', '\\|').replace('\n', ' ')


def table(head, rows):
    if not rows:
        return '_none_\n'
    out = ['| ' + ' | '.join(head) + ' |', '|' + '|'.join('---' for _ in head) + '|']
    out += ['| ' + ' | '.join(cell(c) for c in r) + ' |' for r in rows]
    return '\n'.join(out) + '\n'


def kit_md(m, steps):
    k = m.kit(steps)
    rows = [['part', '`%s` %s' % (p['id'], p['name']), qty(p['qty']), p['step'], p['vendor'] or '—'] for p in k['parts']]
    rows += [['fastener', f['item'], f['qty'], ' '.join(f['steps']), '—'] for f in k['fasteners']]
    rows += [['consumable', c['item'], ('%s %s' % (qty(c['qty']), c['unit'])).strip(), ' '.join(c['steps']), '—']
             for c in k['consumables']]
    rows += [['tool', t['tool'], '', ' '.join(t['steps']), '—'] for t in k['tools']]
    return table(['Kind', 'Item', 'Qty', 'Steps', 'Vendor / file'], rows)


def write(m, out_dir, figinfo, terms, overview):
    meta = m.meta
    allk = m.kit(m.steps)
    mass = sum(float(p.get('mass_g') or 0) for p in m.parts.values() if p.get('flight', True) is not False)
    L_ = []
    a = L_.append
    a('# %s\n' % meta.get('title', 'Build manual'))
    a('`%s` rev %s · %s · status `%s` · generated by `redesign/manual-kit/build_manual.py`. The HTML version '
      '(`manual.html`) adds tick boxes, hover cards and a progress bar.\n' % (meta.get('id', ''), meta.get('revision', ''),
                                                                              meta.get('date', ''), meta.get('status', 'PROPOSED')))
    if meta.get('subtitle'):
        a('%s\n' % meta['subtitle'])
    a(table(['Parameter', 'Value', 'Unit', 'Source'], [
        ['Steps', len(m.steps), '', 'steps.json'], ['Hands-on time', fmt_min(allk['time_min']), '', 'sum of time_min'],
        ['Waiting (cure)', fmt_min(allk['wait_min']), '', 'sum of wait_min'], ['Parts', len(m.parts), '', 'interfaces.json'],
        ['Fasteners', sum(f['qty'] for f in allk['fasteners']), 'pcs', 'joint stacks'],
        ['Flying mass', L.num(mass), 'g', 'interfaces.json mass_g']]))
    if overview.get('cover'):
        a('\n![%s](img/%s)\n' % (overview['cover']['cap'], overview['cover']['file']))
    a('\n**How to read a step:** orange = fit now; own colour = already fitted; see-through = context. Each orange number '
      'in the picture is the action with the same number. Every step ends with a CHECK: measure, write the value, initial.\n')
    a('\n## Safety\n')
    for x in meta.get('safety', []):
        a('- **%s: %s.** %s' % (x.get('level', 'note').capitalize(), x.get('title', ''), md_text(m, x.get('text'))))
    a('\n## Build sequence\n')
    a(table(['Step', 'WP', 'Title', 'Parts fitted', 'Hands-on', 'Wait'],
            [[s['n'], s['wp'], '[%s](#step-%d)' % (s['title'], s['n']), ' '.join('`%s`' % p['id'] for p in s['parts_n']) or '—',
              fmt_min(s.get('time_min')), fmt_min(s.get('wait_min')) if s.get('wait_min') else '—'] for s in m.steps]))
    for g in overview.get('gallery', []):
        a('\n![%s](img/%s)\n' % (g['cap'], g['file']))
    for w in m.wps:
        k = m.kit(w['steps'])
        a('\n## %s · %s\n' % (w['id'], w.get('title', '')))
        a('%s %d steps, %s hands-on, %s waiting.\n' % (w.get('summary', ''), len(w['steps']), fmt_min(k['time_min']),
                                                       fmt_min(k['wait_min'])))
        a('**Kit for %s** (pick before the first step):\n' % w['id'])
        a(kit_md(m, w['steps']))
        for s in w['steps']:
            a('\n### Step %d — %s <a id="step-%d"></a>\n' % (s['n'], s['title'], s['n']))
            a('`%s` · `%s` · %s%s · status `%s`\n' % (s['id'], s['wp'], fmt_min(s.get('time_min')),
                                                       (' + %s wait' % fmt_min(s['wait_min'])) if s.get('wait_min') else '',
                                                       s['status']))
            for i, f in enumerate(s['figures']):
                fi = figinfo.get(f['id'], {})
                if fi.get('svg'):
                    cap = 'FIG %s' % s['id'] if i == 0 else (s.get('details') or [{}])[i - 1].get('title', 'detail')
                    a('![%s](img/%s)\n' % (cap, os.path.basename(fi['svg'])))
            if s.get('goal'):
                a('**Goal:** %s\n' % md_text(m, s['goal']))
            for x in s.get('safety', []):
                a('> **%s** %s\n' % (x.get('level', 'note').capitalize(), md_text(m, x.get('text'))))
            for n, act in enumerate(s['actions_n'], 1):
                a('%d. %s' % (n, md_text(m, act['do'])))
            a('')
            sk = m.kit([s])
            a(table(['Parts', 'Fasteners', 'Tools', 'Consumables'], [[
                '<br>'.join('%sx `%s` %s' % (qty(p['qty']), p['id'], p['name']) for p in sk['parts']) or '—',
                '<br>'.join('%dx %s' % (f['qty'], f['item']) for f in sk['fasteners']) or '—',
                '<br>'.join(t['tool'] for t in sk['tools']) or '—',
                '<br>'.join(('%s %s %s' % (qty(c['qty']), c['unit'], c['item'])).strip() for c in sk['consumables']) or '—']]))
            if s['joints']:
                a('\nJoint stacks:\n')
                a(table(['Edge', 'Joins', 'Fastener', 'Nut / insert', 'Thread mm (min)', 'Torque', 'Tool', 'Access', 'In / out'],
                        [['`%s`' % j['edge'], '`%s` → `%s`' % (j['a'], j['b']),
                          ('%sx %s' % ((j['stack'] or {}).get('count', 1), (j['stack'] or {}).get('fastener'))) if j['stack'] else j['spec'],
                          ', '.join(L.split_list((j['stack'] or {}).get('washer_nut')) + L.split_list((j['stack'] or {}).get('insert'))) or '—',
                          ('%s (%s)' % (j['stack'].get('engagement_mm'), j['stack'].get('min_engagement_mm'))) if j['stack'] else '—',
                          (j['stack'] or {}).get('torque', '—'), (j['stack'] or {}).get('tool', '—'),
                          (j['stack'] or {}).get('access', '—'),
                          ('%s / %s' % (j['stack'].get('install_order', '—'), j['stack'].get('removal_order', '—'))) if j['stack'] else '—']
                         for j in s['joints']]))
            if s['wires']:
                a('\nWiring:\n')
                a(table(['Edge', 'From → to', 'Connector', 'AWG', 'Bend r mm', 'Supports', 'Strain relief', 'Disconnect'],
                        [['`%s`' % w_['edge'], '`%s` → `%s`' % (w_['a'], w_['b']), w_['wire'].get('connector'),
                          w_['wire'].get('gauge_awg'), w_['wire'].get('bend_radius_mm'), '; '.join(w_['wire'].get('support_points', [])),
                          w_['wire'].get('strain_relief'), 'yes' if w_['wire'].get('disconnect') else 'no'] for w_ in s['wires']]))
            for c in s['checks']:
                a('\n> **CHECK** %s  \n> Target: `%s`%s  \n> Measured (%s): ________  ☐ Pass  · initials ____\n'
                  % (md_text(m, c.get('text')), m.sub_params(c.get('target', '')),
                     ('  \n> Target from: %s' % c['source']) if c.get('source') else '', c.get('record', 'value')))
            if s.get('can_go_wrong'):
                a('<details><summary>What can go wrong (%d)</summary>\n' % len(s['can_go_wrong']))
                for g in s['can_go_wrong']:
                    a('- **%s** — %s' % (md_text(m, g.get('problem')), md_text(m, g.get('fix'))))
                a('\n</details>\n')
    a('\n## Kitting list (all work packages)\n')
    for w in m.wps:
        a('\n**%s · %s**\n' % (w['id'], w.get('title', '')))
        a(kit_md(m, w['steps']))
    a('\n## Tool list\n')
    a(table(['Tool', 'Steps'], [[t['tool'], ' '.join(t['steps'])] for t in allk['tools']]))
    a('\n## Parts index\n')
    a(table(['Id', 'Name', 'Status', 'Mass g', 'Vendor / file', 'Fitted in'],
            [['`%s`' % pid, p.get('name', ''), '`%s`' % p.get('status', ''), p.get('mass_g', '—'),
              p.get('csv', {}).get('vendor_or_file', '—'), m.installed_in.get(pid, '`UNVERIFIED` not in any step')]
             for pid, p in sorted(m.parts.items())]))
    a('\n## Glossary\n')
    for t in terms:
        a('- **%s** — %s' % (t['term'], t['def']))
    a('\n## Open items\n')
    for w_ in m.warnings or ['none']:
        a('- %s' % w_)
    with open(os.path.join(out_dir, 'MANUAL.md'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(L_) + '\n')
    # ---- CSVs for kitting and tools
    with open(os.path.join(out_dir, 'kitting.csv'), 'w', encoding='utf-8', newline='') as f:
        wr = csv.writer(f)
        wr.writerow(['wp', 'kind', 'id', 'item', 'qty', 'unit', 'steps', 'make_or_buy', 'vendor_or_file'])
        for w in m.wps:
            k = m.kit(w['steps'])
            for p in k['parts']:
                wr.writerow([w['id'], 'part', p['id'], p['name'], p['qty'], 'pcs', p['step'], p['make_or_buy'], p['vendor']])
            for x in k['fasteners']:
                wr.writerow([w['id'], 'fastener', '', x['item'], x['qty'], 'pcs', ' '.join(x['steps']), 'buy', ''])
            for c in k['consumables']:
                wr.writerow([w['id'], 'consumable', '', c['item'], qty(c['qty']), c['unit'], ' '.join(c['steps']), 'buy', ''])
            for t in k['tools']:
                wr.writerow([w['id'], 'tool', '', t['tool'], 1, 'pcs', ' '.join(t['steps']), 'shop', ''])
    with open(os.path.join(out_dir, 'tools.csv'), 'w', encoding='utf-8', newline='') as f:
        wr = csv.writer(f)
        wr.writerow(['tool', 'work_packages', 'steps'])
        wp_of = {s['id']: s['wp'] for s in m.steps}
        for t in allk['tools']:
            wr.writerow([t['tool'], ' '.join(sorted({wp_of[x] for x in t['steps']})), ' '.join(t['steps'])])
