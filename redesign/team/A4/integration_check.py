"""A4 integration check: run every whole-aircraft check over the delivered subsystems and write INTEGRATION-CHECK.md.

Run (repo root):  python -I redesign/team/A4/integration_check.py

1. merge_check.py on redesign/subsystems (the real merged graph; also refreshes redesign/interfaces/REPORT.md).
2. The same merge "after re-run": every parked edge (edges_pending, harness edges-pending.json) whose parts are now
   all declared is moved into edges, in a temporary copy. What is left there is a real defect, not a stale file.
3. fusion/check.py (CAD stub: registration, touch, floating, keep-outs, transport fit).
4. team/A3/mass_rollup.py --check (roll-up current) and its gate / CG numbers from rollup/rollup.json.
5. interface_plan.py --compare (plan vs declarations -> PLAN-STATUS.md).
Python 3 standard library only; writes nothing outside team/A4 except what merge_check.py writes by design.
"""
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
REDESIGN = HERE.parents[1]
ROOT = REDESIGN.parent
SUBS = REDESIGN / "subsystems"
OUT = HERE / "INTEGRATION-CHECK.md"
sys.path.insert(0, str(REDESIGN / "interfaces"))
import merge_check as mc  # noqa: E402


def run(*args):
    p = subprocess.run([sys.executable, "-I", *map(str, args)], cwd=ROOT, capture_output=True, text=True,
                       encoding="utf-8", errors="replace")
    return p.returncode, p.stdout + p.stderr


def issues(text):
    """(severity, code, item, message) from merge_check / check.py console lines."""
    out = []
    for line in text.splitlines():
        m = re.match(r"\s+(ERROR|WARN)\s+(\S+)\s+(\S+)\s+(.*)$", line)
        if m:
            out.append(m.groups())
    return out


def after_rerun(tmp):
    """Copy every interfaces.json, then move parked edges whose parts are all declared into edges."""
    docs = {}
    for f in SUBS.glob("*/interfaces.json"):
        docs[f.parent.name] = (f.parent, json.loads(f.read_text(encoding="utf-8")))
    declared = {p["id"] for _, d in docs.values() for p in d.get("parts", [])}
    moved = []
    for sub, (folder, d) in docs.items():
        park = list(d.get("edges_pending", []))
        side = folder / "edges-pending.json"
        if side.exists():
            park += json.loads(side.read_text(encoding="utf-8")).get("edges", [])
        keep = []
        for e in park:
            if e.get("part_a") in declared and e.get("part_b") in declared:
                d.setdefault("edges", []).append({k: v for k, v in e.items() if k != "waits_for"})
                moved.append((sub, e["id"]))
            else:
                keep.append(e)
        d["edges_pending"] = keep
        (tmp / sub).mkdir(parents=True)
        (tmp / sub / "interfaces.json").write_text(json.dumps(d, indent=1), encoding="utf-8")
    return moved


def table(rows, head):
    L = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    L += ["| " + " | ".join(str(c).replace("|", "/") for c in r) + " |" for r in rows]
    return L


def summarise(iss):
    cnt = {}
    for sev, code, item, msg in iss:
        cnt.setdefault((sev, code), []).append(item)
    return [(s, c, len(v), " ".join("`%s`" % x for x in sorted(set(v))[:12]) + (" …" if len(set(v)) > 12 else ""))
            for (s, c), v in sorted(cnt.items())]


def main():
    rc1, t1 = run(REDESIGN / "interfaces" / "merge_check.py", "--budget", REDESIGN / "params" / "mass_budget.json")
    tmp = Path(tempfile.mkdtemp(prefix="a4_rerun_"))
    try:
        moved = after_rerun(tmp / "subs")
        rc2, t2 = run(REDESIGN / "interfaces" / "merge_check.py", "--root", tmp / "subs", "--out", tmp / "out",
                      "--budget", REDESIGN / "params" / "mass_budget.json")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    rc3, t3 = run(REDESIGN / "fusion" / "check.py")
    rc4, t4 = run(REDESIGN / "team" / "A3" / "mass_rollup.py", "--check")
    rc5, t5 = run(HERE / "interface_plan.py", "--compare")
    head1 = next((l for l in t1.splitlines() if l.startswith("merge_check:")), "")
    tail1 = [l for l in t1.splitlines() if l.startswith("merge_check:")][-1:]
    tail2 = [re.sub(r"; wrote .*", "", l) for l in t2.splitlines() if l.startswith("merge_check:")][-1:]
    tail3 = [l for l in t3.splitlines() if l.startswith("check:")][-1:]
    total3 = [l for l in t3.splitlines() if l.startswith("TOTAL")][:1]
    roll = {}
    try:
        roll = json.loads((REDESIGN / "team" / "A3" / "rollup" / "rollup.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        pass
    L = ["# Integration check (A4)", "",
         "Generated by `python -I redesign/team/A4/integration_check.py`. Do not edit by hand. Findings and owners: "
         "`SUMMARY.md` and `CHANGE-REQUESTS.md` (round 4).", "",
         "| # | Check | Result | Line |", "|---|---|---|---|",
         "| 1 | merge_check.py (real graph) | %s | %s |" % ("PASS" if rc1 == 0 else "FAIL", (tail1 or [""])[0]),
         "| 2 | merge_check.py after owners re-run their generators (%d parked edges moved) | %s | %s |" % (
             len(moved), "PASS" if rc2 == 0 else "FAIL", (tail2 or [""])[0]),
         "| 3 | fusion/check.py | %s | %s; %s |" % ("PASS" if rc3 == 0 else "FAIL", (total3 or [""])[0], (tail3 or [""])[0]),
         "| 4 | A3 mass_rollup.py --check | %s | %s |" % ("PASS" if rc4 == 0 else "FAIL", t4.strip().splitlines()[-1] if t4.strip() else ""),
         "| 5 | interface_plan.py --compare | %s | %s |" % ("PASS" if rc5 == 0 else "FAIL", t5.strip().splitlines()[-1] if t5.strip() else ""),
         ""]
    L += ["## 1. Real merged graph", "", head1, ""] + table(summarise(issues(t1)), ["Sev", "Code", "n", "Items"]) + [""]
    L += ["## 2. After the owners re-run (parked edges moved in)", "",
          "Moved: " + (", ".join("`%s`" % e for _, e in moved) or "none") + ".", ""]
    L += table(summarise(issues(t2)), ["Sev", "Code", "n", "Items"]) + [""]
    L += ["## 3. CAD stub (fusion/check.py)", ""] + table(summarise(issues(t3)), ["Sev", "Code", "n", "Items"]) + [""]
    if roll:
        m, c = roll.get("mass", {}), roll.get("cg", {})
        rng = (REDESIGN / "params" / "params.json")
        xr = json.loads(rng.read_text(encoding="utf-8"))["cg"]["x_range_m"]["value"]
        cgx = (c.get("cg_m") or [None])[0]
        rows = [("Basic mass", "%.0f" % (1000 * m.get("basic_kg", 0)), "g", "—", "A3 `rollup.json`"),
                ("Predicted mass (with growth)", "%.0f" % (1000 * m.get("predicted_kg", 0)), "g", "≤ 2 600 gate",
                 "PASS" if m.get("gate_margin_kg", -1) >= 0 else "FAIL"),
                ("Gate margin, heaviest pack listing", "%.0f" % (1000 * m.get("gate_margin_pack_heavy_kg", 0)), "g", "≥ 100 g overrun cover",
                 "PASS" if m.get("gate_margin_pack_heavy_kg", 0) >= 0.1 else "FAIL"),
                ("CG x take-off", "%.4f" % cgx if cgx is not None else "—", "m", "%.3f…%.3f" % tuple(xr),
                 "PASS" if cgx is not None and xr[0] <= cgx <= xr[1] else "FAIL"),
                ("Worst allocation ratio", "%.2f (%s)" % (m.get("worst_alloc_ratio", 0), m.get("worst_alloc_subsystem")), "—", "≤ 1.00",
                 "PASS" if m.get("worst_alloc_ratio", 9) <= 1 else "FAIL")]
        L += ["## 4. Mass roll-up (A3)", ""] + table(rows, ["Item", "Value", "Unit", "Limit", "Result"]) + [""]
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("integration_check: merge %s, after re-run %s, check.py %s, roll-up %s, compare %s -> %s" % tuple(
        ["PASS" if r == 0 else "FAIL" for r in (rc1, rc2, rc3, rc4, rc5)] + [OUT.relative_to(REDESIGN).as_posix()]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
