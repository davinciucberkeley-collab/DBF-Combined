GEO = {"D": P + "wing.spar.od_m", "d": P + "wing.spar.id_m"}


@kit.calc("CALC-C2-SPAR-ROOT", title="Spar root bending stress, spar alone",
          equation="sigma = Mb_ult (D/2) / I;  I = pi/64 (D^4 - d^4)",
          inputs={"Mb": "CL-C1-SPAR-MB-ULT", **GEO}, assumes=["ASM-C2-SPAR-SIGMA"], cites=["SRC-C2-ROARK"])
def spar_root(Mb, D, d):
    I_ = math.pi / 64 * (D ** 4 - d ** 4)
    return {"sigma_pa": Mb * D / 2 / I_, "I_m4": I_}


@kit.calc("CALC-C2-SPAR-TAU", title="Spar shear stress, torsion + transverse shear, spar alone",
          equation="tau = T r / J + 2 V / A", inputs={"T": "CL-C1-WING-TORSION-ULT", "V": "CL-C1-WING-SHEAR-ULT", **GEO})
def spar_tau(T, V, D, d):
    J = math.pi / 32 * (D ** 4 - d ** 4)
    A = math.pi / 4 * (D ** 2 - d ** 2)
    return T * D / 2 / J + 2 * V / A


@kit.calc("CALC-C2-SPAR-BUCKLE", title="Spar local buckling stress in bending",
          equation="sigma_cr = 0.6 gamma E_lo t / R, gamma 0.5", cites=["SRC-C2-ROARK"],
          inputs={"E": I + "spar_E_lo_pa", **GEO})
def spar_buckle(E, D, d):
    t = (D - d) / 2
    R = (D + d) / 4
    return 0.6 * 0.5 * E * t / R


@kit.calc("CALC-C2-SPAR-BRACE", title="Spar between brace anchor and block, brace couple added",
          equation="sigma = (Mx_ult + F_brace/(1.15 x 1.25) x (y_fin - 0.242)) (D/2) / I",
          inputs={"Mx": "CL-C1-SPAR-MX-ULT", "Fb": F + "F_brace_design_N", "y_fin": P + "fins.y_m", **GEO})
def spar_brace(Mx, Fb, y_fin, D, d):
    I_ = math.pi / 64 * (D ** 4 - d ** 4)
    return (Mx + Fb / (1.15 * 1.25) * (y_fin - 0.242)) * D / 2 / I_


@kit.calc("CALC-C2-AE-REQ", title="Required aeroelastic clearance speed", equation="V_req = 1.2 VD",
          inputs={"VD": "CL-C1-VD-ENV", "k": "ASM-C2-AE-FACTOR"})        # CR-C1-28: the speed the structure is cleared to
def ae_req(VD, k):
    return k * VD


@kit.calc("CALC-C2-DEFL", title="Tip deflection ratio at limit load (beam integration of every C1 case)",
          equation="w_tip_max / (b/2)", inputs={"w": F + "w_tip_env_m", "b": P + "wing.span_m"})
def defl(w, b):
    return w / (b / 2)


@kit.calc("CALC-C2-MASS", title="Wing structure mass", equation="m = core + tape + spar + fill + plugs",
          inputs={"m": F + "wing_mass_kg"})
def wing_mass(m):
    return m * 1000.0


def passthrough(cid, title, ref, eq="value from wing_struct.py"):
    def _f(v):
        return v
    _f.__name__ = _f.__qualname__ = "pt_" + cid.replace("-", "_").lower()
    globals()[_f.__name__] = _f
    return kit.calc(cid, title=title, equation=eq, inputs={"v": ref})(_f)


