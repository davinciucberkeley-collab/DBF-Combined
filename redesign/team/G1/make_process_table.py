"""G1 manufacturing engineer: classifies every line of every subsystems/*/parts.csv into one allowed process family (R-PROCESS).

Run:  python -I redesign/team/G1/make_process_table.py        -> PROCESS-TABLE.md beside this file
R-PROCESS (team/A2/REQUIREMENTS.md): every part is bought or made by hot-wire XPS from templates, packing-tape skin, knife- or laser-cut
foam board, FDM PETG or PLA, epoxy or CA bonds, standard fasteners, hand-cut CF tube; no composite lay-up, no machining beyond drilling;
printed parts <= 0.2 m on any axis. The keyword rules below are the classification (data, not analysis); anything they cannot place, or
that names a forbidden process, is listed under Exceptions instead of being forced into a family.
"""
import csv
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
R = HERE.parents[1]
SUBS = ("wing", "fins", "pod", "landing", "mechanisms", "power", "avionics", "harness", "propulsion", "transport", "ground")
FORBIDDEN = ("lay-up", "layup", "machin", "cnc", "mill", "lathe", "router")

# (family, test on lower-cased process + material); first match wins
RULES = [
    ("hot-wire XPS (templates, Jacobs: not listed, bought gear G11/H05)", lambda p, m, mb: "hot-wire" in p or "hot wire" in p),
    ("FDM print (PETG / ASA / TPU, see G3 print list)", lambda p, m, mb: mb == "make" and ("fdm" in p or "3d print" in p or "printed" in p or "(printed)" in m)),
    ("packing-tape skin / hand-laid tape", lambda p, m, mb: mb == "make" and ("tape" in p or "strips" in p)),
    ("knife- or laser-cut foam board, laminated", lambda p, m, mb: mb == "make" and ("foam board" in m or "laminate" in p)),
    ("laser-cut ply / print-and-laminate", lambda p, m, mb: mb == "make" and ("laser" in p or "birch" in m or "paper" in m)),
    ("Coroplast score and fold, PE foam cut", lambda p, m, mb: mb == "make" and ("scored" in p or "coroplast" in m or "pe foam" in m or "saddle" in p)),
    ("epoxy / microballoon bond or fillet", lambda p, m, mb: mb == "make" and ("epoxy" in m or "epoxy" in p or "fillet" in p or "bead" in p)),
    ("electrical: cut, twist, solder, crimp (Electronics Lab)", lambda p, m, mb: mb == "make" and ("solder" in p or "crimp" in p or "shear fr4" in p)),
    ("hand-cut foam, sheet and tube liners (knife, scissors, saw, fence)", lambda p, m, mb: mb == "make" and ("xps" in m or "foam" in m or "cut" in p or "scissors" in p or "knife" in p or "straw liner" in p)),
    ("bought, then cut / drilled / soldered to size", lambda p, m, mb: mb == "buy" and any(k in p for k in ("cut", "drill", "solder", "scuff", "trim", "re-terminate", "flash", "bond"))),
    ("bought, used as supplied (fasteners, wire, electronics, consumables)", lambda p, m, mb: mb == "buy"),
]


def main():
    fam = defaultdict(list)
    exc = []
    per_sub = defaultdict(lambda: defaultdict(int))
    n = 0
    for sub in SUBS:
        f = R / "subsystems" / sub / "parts.csv"
        if not f.exists():
            continue
        for r in csv.DictReader(open(f, encoding="utf-8")):
            n += 1
            p, m, mb = ((r["process"] or "") + " " + (r["name"] or "")).lower(), (r["material"] or "").lower(), (r["make_or_buy"] or "").lower()
            bad = [k for k in FORBIDDEN if k in p]
            if bad and "router" not in bad and "drill" not in p:
                exc.append((sub, r["part_id"], r["name"], f"names {', '.join(bad)} in its process text: {r['process'][:80]}"))
            hit = None
            for name, test in RULES:
                if test(p, m, mb):
                    hit = name
                    break
            if hit is None:
                exc.append((sub, r["part_id"], r["name"], f"no rule matches (make_or_buy={mb}, process='{r['process'][:60]}')"))
                continue
            fam[hit].append((sub, r["part_id"], r["name"], int(float(r["qty"] or 1))))
            per_sub[sub][hit] += 1
    out = [f"# G1 process table: every parts.csv line to one allowed process family\n",
           "Revision G1-R2, 2026-11-13 (CDR fix round: part ids per family listed; D-89c parts FIN-013 strap eye and MEC-013 horn backplate included). Generated by `python -I redesign/team/G1/make_process_table.py` from `subsystems/*/parts.csv` (data: the CAD parts lists). Evidence for `R-PROCESS`.\n",
           f"{n} part lines read from {len([s for s in SUBS if (R / 'subsystems' / s / 'parts.csv').exists()])} subsystems; **{len(exc)} exception(s)** (below).\n",
           "| Process family | Lines | Subsystems |", "|---|---|---|"]
    for name, _ in RULES:
        ls = fam.get(name, [])
        out.append(f"| {name} | {len(ls)} | {', '.join(sorted({s for s, *_ in ls})) or '-'} |")
    out += ["", "## Lines per subsystem and family", "", "| Subsystem | " + " | ".join(f"F{i + 1}" for i in range(len(RULES))) + " |", "|---|" + "---|" * len(RULES)]
    for sub in SUBS:
        if sub in per_sub:
            out.append(f"| {sub} | " + " | ".join(str(per_sub[sub].get(name, 0) or "") for name, _ in RULES) + " |")
    out += ["", "Family key: " + "; ".join(f"F{i + 1} = {name}" for i, (name, _) in enumerate(RULES))]
    # G1-R2 (CDR-23, CDR-BT-14 d): name every part id, so a part added to a parts.csv (e.g. FIN-013, MEC-013, D-89c) is visible here
    out += ["", "## Part ids per family", "", "| Family | Part ids |", "|---|---|"]
    for i, (name, _) in enumerate(RULES):
        ls = fam.get(name, [])
        if ls:
            out.append(f"| F{i + 1} | " + ", ".join(f"`{pid}`" for _, pid, _, _ in ls) + " |")
    out += ["", "## Exceptions (need a G1 decision or a parts.csv fix)", ""]
    if exc:
        out += ["| Subsystem | Part | Name | Why |", "|---|---|---|---|"] + [f"| {a} | {b} | {c[:60]} | {d} |" for a, b, c, d in exc]
    else:
        out.append("None.")
    out += ["", "## Notes", "",
            "- Drilling is the only machining: motor-mount holes from a printed guide (never through the motor), pin holes through strip and laminate, brass-tube cartridge bores.",
            "- The wing-core slot may be cut with a heated U-wire on a rail or a router with a ball bit (`wing/BUILD.md`); the router is hand-held woodshop work, not machining of a flight part to tolerance, and is allowed only as the fallback to the hot-tool route. G1 decision: hot tool first.",
            "- Hot-wire gear is bought (`G11`, `H05`); Jacobs lists no hot-wire cutter (labs-and-equipment page, checked 2026-11-13)."]
    (HERE / "PROCESS-TABLE.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("lines", n, "exceptions", len(exc))
    for e in exc:
        print(e)


if __name__ == "__main__":
    main()
