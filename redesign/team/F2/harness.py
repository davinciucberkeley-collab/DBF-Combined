# ============================================================================ figure (design-system diagram style)
def figure(g, wires, grooves):
    S1 = 1200.0                       # px per m, top view
    W = 1200
    ox, oy = 40, 204                  # top view origin: y = 0 at ox, x = 0 at oy (nose up; pod nose at x -0.115)
    zU = g["zU"]

    def T(x, y):
        return ox + y * S1, oy + x * S1

    col = {"PWR": "#E0613A", "SIG": "#4C8DE0", "SRV": "#5DB24D", "PH": "#E0613A", "GPS": "#8E6FD8"}
    els = []
    # wing outline (right half, shown to y 0.42)
    x0, y0 = T(0, 0)
    x1, y1 = T(g["c"], 0.42)
    els.append('<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="#4C8DE0" fill-opacity="0.08" '
               'stroke="#121619" stroke-width="1.5"/>' % (x0, y0, x1 - x0, y1 - y0))
    # spar slot (hidden)
    a, b = T(g["x_spar"] - g["r_slot"], 0)
    c, d = T(g["x_spar"] + g["r_slot"], 0.42)
    els.append('<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="none" stroke="#5A6472" '
               'stroke-width="0.75" stroke-dasharray="6 4"/>' % (a, b, c - a, d - b))
    # pod
    a, b = T(g["pod_x0"], 0)
    c, d = T(g["pod_x1"], g["pod_hw"])
    els.append('<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="#7F8C9E" fill-opacity="0.25" '
               'stroke="#121619" stroke-width="1.5"/>' % (a, b, c - a, d - b))
    # fin and block
    a, b = T(g["x_tube"], g["y_in"])
    c, d = T(g["c"], g["y_out"])
    els.append('<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="#2BA6A0" fill-opacity="0.35" '
               'stroke="#121619" stroke-width="1.5"/>' % (a, b, c - a, d - b))
    a, b = T(0.028, g["block_y_in"])
    c, d = T(0.097, g["yf"] + 0.018)
    els.append('<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="none" stroke="#121619" '
               'stroke-width="0.75"/>' % (a, b, c - a, d - b))
    cx, cy = T(g["x_tube"], g["yf"])
    els.append('<circle cx="%.1f" cy="%.1f" r="%.1f" fill="#121619" fill-opacity="0.2" stroke="#121619" '
               'stroke-width="1.5"/>' % (cx, cy, g["r_tube"] * S1))
    # GPS mast top
    gx, gy = T(g["gps"][0], 0)
    els.append('<circle cx="%.1f" cy="%.1f" r="6" fill="none" stroke="#121619" stroke-width="1.25"/>' % (gx, gy))
    # routes (right side only, top view)
    for w in wires:
        kind = w[0].split("-")[1]
        if kind not in col or (w[0][-2:] in ("UL", "LL") or w[0].endswith(("-L", "-L-P"))):
            continue
        dash = ' stroke-dasharray="5 3"' if w[0][-2:] == "LR" else ""
        pts = " ".join("%.1f,%.1f" % T(p[0], p[1]) for p in w[9] if p[1] >= -0.001)
        els.append('<polyline points="%s" fill="none" stroke="%s" stroke-width="2"%s/>' % (pts, col[kind], dash))
    gps = [w for w in wires if w[0] == "W-GPS"][0]
    els.append('<polyline points="%s" fill="none" stroke="%s" stroke-width="2"/>' % (
        " ".join("%.1f,%.1f" % T(p[0], max(p[1], 0)) for p in gps[9]), col["GPS"]))

    def label(x, y, text, dx=6, dy=-6, anchor="start"):
        px, py = T(x, y)
        els.append('<text x="%.1f" y="%.1f" font-family="IBM Plex Mono, monospace" font-size="12" fill="#121619" '
                   'text-anchor="%s">%s</text>' % (px + dx, py + dy, anchor, text))
    label(grooves["x_pos_m"], 0.20, "grooves: sig %.0f · + %.0f · − %.0f mm" % (
        grooves["x_sig_m"] * 1000, grooves["x_pos_m"] * 1000, grooves["x_neg_m"] * 1000), dy=-14)
    label(grooves["x_servo_m"], 0.20, "servo groove x %.0f mm" % (grooves["x_servo_m"] * 1000), dy=16)
    label(g["x_spar"], 0.36, "spar slot", dy=4)
    label(-0.08, 0.005, "pod", dy=0)
    label(g["gps"][0], 0.0, "GPS mast", dx=10, dy=4)
    label(grooves["fin_hole_x_m"], g["yf"], "fin hole", dx=-8, dy=26, anchor="end")
    label(0.06, g["pod_hw"] + 0.008, "P1", dx=4, dy=18)
    label(0.2, g["yf"], "fin", dx=10, dy=4)
    # scale bar
    sx, sy = T(0.30, 0.0)
    els.append('<line x1="%.1f" y1="%.1f" x2="%.1f" y2="%.1f" stroke="#121619" stroke-width="1"/>' % (
        ox, oy + 0.335 * S1, ox + 0.1 * S1, oy + 0.335 * S1))
    els.append('<text x="%.1f" y="%.1f" font-family="IBM Plex Mono, monospace" font-size="11" fill="#121619">'
               '0 — 100 mm</text>' % (ox, oy + 0.335 * S1 + 14))
    els.append('<text x="%d" y="40" font-family="IBM Plex Sans, system-ui" font-size="12" font-weight="500" '
               'fill="#121619">TOP · right half, nose up</text>' % ox)

    # ---- fin outboard face (x right, z up), right fin
    S2 = 1250.0
    fx0, fz0 = 720, 340

    def U(x, z):
        return fx0 + (x - 0.0) * S2, fz0 - z * S2
    a, b = U(g["x_tube"], 0.21)
    c, d = U(g["c"], -0.21)
    els.append('<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="#2BA6A0" fill-opacity="0.18" '
               'stroke="#121619" stroke-width="1.5"/>' % (a, b, c - a, d - b))
    a, b = U(0, zU(0.08))
    c, d = U(g["c"], g["zL"](0.08))
    els.append('<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="#4C8DE0" fill-opacity="0.12" '
               'stroke="#121619" stroke-width="1"/>' % (a, b, c - a, d - b))
    for sz in (1, -1):
        a, b = U(g["esc_x0"], sz * g["esc_z"] + 0.014)
        c, d = U(g["esc_x1"], sz * g["esc_z"] - 0.014)
        els.append('<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="#E0613A" fill-opacity="0.35" '
                   'stroke="#121619" stroke-width="1.25"/>' % (a, min(b, d), c - a, abs(d - b)))
        mx, mz = U(g["x_face"] - 0.013, sz * g["zm"])
        els.append('<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="#121619" fill-opacity="0.25" '
                   'stroke="#121619" stroke-width="1.25"/>' % (mx, mz - 0.019 * S2, 0.026 * S2, 0.038 * S2))
        hx, hz = U(grooves["fin_hole_x_m"], sz * (abs((zU if sz > 0 else g["zL"])(grooves["fin_hole_x_m"]))
                                                   + grooves["fin_hole_dz_m"]))
        els.append('<circle cx="%.1f" cy="%.1f" r="%.1f" fill="none" stroke="#121619" stroke-width="1.25"/>' % (
            hx, hz, 0.005 * S2))
        cx1, cz1 = U(g["x_tube"], sz * g["collar_z"])
        els.append('<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="none" stroke="#121619" '
                   'stroke-width="0.75"/>' % (cx1 - 0.011 * S2, cz1 - 0.008 * S2, 0.062 * S2, 0.016 * S2))
    a, b = U(g["x_tube"] - g["r_tube"], 0.172)
    els.append('<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="#121619" fill-opacity="0.15" '
               'stroke="#121619" stroke-width="1"/>' % (a, b, 2 * g["r_tube"] * S2, 0.344 * S2))
    for w in wires:
        kind = w[0].split("-")[1]
        if kind not in ("PWR", "SIG", "PH") or not w[0].endswith(("UR", "LR")):
            continue
        pts = [p for p in w[9] if p[1] >= g["y_in"] - 0.004]
        if len(pts) < 2:
            continue
        els.append('<polyline points="%s" fill="none" stroke="%s" stroke-width="2"/>' % (
            " ".join("%.1f,%.1f" % U(p[0], p[2]) for p in pts), col[kind]))

    def lab2(x, z, text, dx=6, dy=4, anchor="start"):
        px, pz = U(x, z)
        els.append('<text x="%.1f" y="%.1f" font-family="IBM Plex Mono, monospace" font-size="12" fill="#121619" '
                   'text-anchor="%s">%s</text>' % (px + dx, pz + dy, anchor, text))
    lab2(g["esc_x1"], g["esc_z"], "ESC UR", dx=24)
    lab2(g["esc_x1"], -g["esc_z"], "ESC LR", dx=24)
    lab2(g["x_face"] - 0.013, g["zm"] + 0.026, "motor UR", dx=0, anchor="start")
