def seg_len(points):
    return [math.dist(a[:3], b[:3]) for a, b in zip(points, points[1:])]


def helix(od_mm, lay_m):
    """Length factor of a conductor in a twisted pair: helix of diameter = conductor OD, pitch = lay length."""
    return math.sqrt(1.0 + (math.pi * od_mm / 1000.0 / lay_m) ** 2) if lay_m else 1.0


def path_len(row, od_table):
    """Cut length of one conductor (m) and the harness-supplied length (cut minus factory lead)."""
    _wid, _eid, awg, _n, tw, lay, loop, _gpm, factory, pts = row
    od = dict((int(a), b) for a, b in od_table).get(int(awg), 1.0)
    L = 0.0
    for s, a in zip(seg_len(pts), pts):
        L += s * (helix(od, lay) if tw and a[3] in ("P", "B", "M", "L") else 1.0)
    cut = L + loop
    return cut, max(0.0, cut - factory)


