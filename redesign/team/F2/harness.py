    out["esc_max"] = max(out["esc_" + s] for s in STATIONS)
    out["esc_min"] = min(out["esc_" + s] for s in STATIONS)
    out["phase_reach_max"] = max(out["phase_reach_" + s] for s in STATIONS)
    out["dshot_max"] = max(out["dshot_" + s] for s in STATIONS)
    out["main_path"] = cut["W-MAIN-1"] + cut["W-MAIN-2"]
    out["main_1"], out["main_2"] = cut["W-MAIN-1"], cut["W-MAIN-2"]
    out["i2c_total"] = cut["W-GPS"] + cut["W-ASPD"]
    out["rx"] = cut["W-RX"]
