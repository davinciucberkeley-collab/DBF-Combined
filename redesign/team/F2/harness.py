# A wire-table row: [wire_id, edge_id, awg, n_cond, twisted, lay_m, loop_m, gpm, factory_m, points]
# points: [[x, y, z, code], ...]


def seg_len(points):
    return [math.dist(a[:3], b[:3]) for a, b in zip(points, points[1:])]


def helix(od_mm, lay_m):
    """Length factor of a conductor in a twisted pair: helix of diameter = conductor OD, pitch = lay length."""
    return math.sqrt(1.0 + (math.pi * od_mm / 1000.0 / lay_m) ** 2) if lay_m else 1.0


def path_len(row, od_table):
    """Cut length of one conductor (m) and the harness-supplied length (cut minus factory lead)."""
    _wid, _eid, awg, _n, tw, lay, loop, _gpm, factory, pts = row
    od = dict((int(a), b) for a, b in od_table).get(int(awg), 1.0)
    L = 0.0
    for s, a in zip(seg_len(pts), pts):
        L += s * (helix(od, lay) if tw and a[3] in ("P", "B", "M", "L") else 1.0)
    cut = L + loop
    return cut, max(0.0, cut - factory)


def lengths(wires, od):
    """Routed lengths the other roles asked for (F1 ESC leads, F3 I2C, F5 RX, E1 phase reach, F1 main path)."""
    by = {r[0]: r for r in wires}
    cut = {k: path_len(r, od)[0] for k, r in by.items()}
    out = {}
    for st in STATIONS:
        out["esc_" + st] = cut["W-PWR-" + st]
        out["phase_reach_" + st] = cut["W-PH-" + st]
        out["dshot_" + st] = cut["W-SIG-" + st + "-P"] + cut["W-SIG-" + st]
    out["esc_max"] = max(out["esc_" + s] for s in STATIONS)
    out["esc_min"] = min(out["esc_" + s] for s in STATIONS)
    out["phase_reach_max"] = max(out["phase_reach_" + s] for s in STATIONS)
    out["dshot_max"] = max(out["dshot_" + s] for s in STATIONS)
    out["main_path"] = cut["W-MAIN-1"] + cut["W-MAIN-2"]
    out["main_1"], out["main_2"] = cut["W-MAIN-1"], cut["W-MAIN-2"]
    out["i2c_total"] = cut["W-GPS"] + cut["W-ASPD"]
    out["rx"] = cut["W-RX"]
    out["servo_max"] = max(sum(cut.get("W-SRV-%s%s" % (s, e), 0.0) for e in ("-P", "", "-S")) for s in "LR")
    out["cap_lead_max"] = max(cut["W-CAP-" + s] for s in STATIONS)
    out["ubec_feed"] = cut["W-FUSE-IN"] + cut["W-UBEC-IN"]
    return out


def mass_points(wires, od, fittings):
    """Harness mass as point masses (g, [x, y, z]): wire mass spread along each segment in <= 10 mm pieces (service
    loop split to both ends), fittings at their stations. Rows with gpm 0 are carried by another subsystem (pack
    lead: pack; 10 AWG main jumpers and cap legs: power; servo's own lead: mechanisms)."""
    out = []
    for row in wires:
        _wid, _eid, awg, n, tw, lay, loop, gpm, factory, pts = row
        if not gpm:
            continue
        cut, supplied = path_len(row, od)
        if supplied <= 0:
            continue
        k = supplied / cut                                    # factory lead: harness supplies only part of it
        segs = seg_len(pts)
        tot = sum(segs) or 1.0
        for s, a, b in zip(segs, pts, pts[1:]):
            npc = max(1, math.ceil(s / 0.010))
            for j in range(npc):
                t = (j + 0.5) / npc
                out.append((gpm * n * s / tot * (cut - loop) * k / npc, [a[i] + t * (b[i] - a[i]) for i in range(3)]))
        out.append((gpm * n * loop * k / 2, list(pts[0][:3])))
        out.append((gpm * n * loop * k / 2, list(pts[-1][:3])))
    for _name, qty, g_each, x, y, z in fittings:
        out.append((qty * g_each, [x, y, z]))
    return out


def mass_cg(wires, od, fittings, pod_box):
    """Harness mass (g) and CG, total and per bundle part (HRN-001 inside the pod box, HRN-002-R/L outside)."""
    groups = {"HRN-001": [0.0, 0.0, 0.0, 0.0], "HRN-002-R": [0.0, 0.0, 0.0, 0.0], "HRN-002-L": [0.0, 0.0, 0.0, 0.0]}
    for m, p in mass_points(wires, od, fittings):
        g = bundle_of(p, pod_box)
        groups[g][0] += m
        for i in range(3):
            groups[g][i + 1] += m * p[i]
    total = sum(v[0] for v in groups.values())
    cg = [sum(v[i + 1] for v in groups.values()) / total for i in range(3)]
    parts = {k: {"mass_g": v[0], "cg": [v[i + 1] / v[0] for i in range(3)] if v[0] else None}
             for k, v in groups.items()}
    return total, cg, parts


def bundle_of(p, pod_box):
    (x0, x1), ymax, z0 = pod_box
    if x0 - 0.001 <= p[0] <= x1 + 0.0015 and abs(p[1]) <= ymax + 0.0005 and p[2] >= z0 - 0.001:
        return "HRN-001"
    return "HRN-002-R" if p[1] >= 0 else "HRN-002-L"


BUNDLE_RHO_G_M3 = 3.0e6        # mean density of a silicone-wire bundle (16 AWG pair: 32 g/m in about 10.6 mm2), EST
LEG_DIA_M = (0.002, 0.012)     # CAD bundle-leg diameter clamp


def _seg_dist(p, a, b):
    d = [b[i] - a[i] for i in range(3)]
    L2 = sum(v * v for v in d) or 1e-12
    t = max(0.0, min(1.0, sum((p[i] - a[i]) * d[i] for i in range(3)) / L2))
    return math.dist(p, [a[i] + t * d[i] for i in range(3)])


def bodies(wires, od, fittings, pod_box, legs):
    """CAD bundle legs sized by the harness mass nearest to each (right side only; the left bundle is its mirror):
    d = sqrt(4 m / (pi L rho)), clamped. Returns the legs with their diameters, each bundle's body centroid (the
    volume centroid fusion/check.py measures) and its gap to the wire-mass CG."""
    key_of = {"HRN-001": "pod", "HRN-002-R": "side_R"}
    m_leg = {k: [0.0] * len(v) for k, v in legs.items()}
    for m, p in mass_points(wires, od, fittings):
        k = key_of.get(bundle_of(p, pod_box))
        if k is None:                                          # left side: the body is the mirror of the right
            continue
        i = min(range(len(legs[k])), key=lambda j: _seg_dist(p, legs[k][j][0], legs[k][j][1]))
        m_leg[k][i] += m
    out, cgb = {}, {}
    for k, v in legs.items():
        rows, vol, mom = [], 0.0, [0.0, 0.0, 0.0]
        for (a, b, *_d), m in zip(v, m_leg[k]):
            L = math.dist(a, b) or 1e-6
            d = min(LEG_DIA_M[1], max(LEG_DIA_M[0], math.sqrt(4 * m / (math.pi * L * BUNDLE_RHO_G_M3))))
            rows.append([a, b, d])
            vv = d * d * L
            vol += vv
            for i in range(3):
                mom[i] += vv * (a[i] + b[i]) / 2
        out[k] = rows
        cgb[k] = [mom[i] / vol for i in range(3)]
    _m, _cg, parts = mass_cg(wires, od, fittings, pod_box)
    body = {"HRN-001": cgb["pod"], "HRN-002-R": cgb["side_R"],
            "HRN-002-L": [cgb["side_R"][0], -cgb["side_R"][1], cgb["side_R"][2]]}
    gap = {pid: math.dist(body[pid], parts[pid]["cg"]) for pid in body}
    return {"legs": out, "leg_mass_g": m_leg, "body_cg": body, "gap": gap, "cg_gap_max": max(gap.values())}


def bends(wires, od, k_table):
    """Smallest ratio (largest fillet radius the polyline allows / required radius) over every corner > 5 deg.
    Formed parts owned by another role are skipped: the 10 AWG main jumpers (F1 CL-PWR-BEND, 2 x OD formed before
    soldering), the pack's own lead (pack) and the cap legs (F1)."""
    kd = dict((int(a), b) for a, b in k_table)
    odd = dict((int(a), b) for a, b in od)
    worst = (1e9, "")
    for row in wires:
        wid, awg, pts = row[0], int(row[2]), row[9]
        if wid in OTHER_FORMED or wid.startswith("W-CAP-"):
            continue
        r_req = kd.get(awg, 3.0) * odd.get(awg, 1.0) / 1000.0
        segs = seg_len(pts)
        for i in range(1, len(pts) - 1):
            a, b, c = (pts[i - 1][:3], pts[i][:3], pts[i + 1][:3])
            u = [b[j] - a[j] for j in range(3)]
            v = [c[j] - b[j] for j in range(3)]
            nu, nv = math.hypot(*u), math.hypot(*v)
            if nu < 1e-9 or nv < 1e-9:
                continue
            cosang = max(-1.0, min(1.0, sum(u[j] * v[j] for j in range(3)) / nu / nv))
            th = math.acos(cosang)
            if th < math.radians(5):
                continue
            t_prev = segs[i - 1] * (1.0 if i - 1 == 0 else 0.5)
            t_next = segs[i] * (1.0 if i + 1 == len(pts) - 1 else 0.5)
            r_max = min(t_prev, t_next) / math.tan(th / 2)
            ratio = r_max / r_req
            if ratio < worst[0]:
                worst = (ratio, "%s corner %d (%.0f deg, r_max %.1f mm, needs %.1f mm)" % (
                    wid, i, math.degrees(th), r_max * 1000, r_req * 1000))
    return worst


def free_span(wires):
    """Longest run of consecutive free-air (F) segments, and longest tape-strip (B) segment between strips."""
    worst_f, worst_b = 0.0, 0.0
    for row in wires:
        pts, run = row[9], 0.0
        for s, a in zip(seg_len(pts), pts):
            if a[3] in ("F", "T"):
                run = s if a[3] == "T" else run + s                # a tie point starts a new free span
                worst_f = max(worst_f, run)
            else:
                run = 0.0
    return worst_f


def mast_clear(wires, gps_xyz):
    """Nearest point of any wing-groove ESC power segment to the GPS mast top (F3: >= 0.12 m)."""
    best = 1e9
    for row in wires:
        if not row[0].startswith("W-PWR-"):
            continue
        for a, b in zip(row[9], row[9][1:]):
            if a[3] != "G":
                continue
            for t in [i / 20 for i in range(21)]:
                p = [a[j] + t * (b[j] - a[j]) for j in range(3)]
                best = min(best, math.dist(p, gps_xyz))
    return best


