BUNDLE_K = {1: 1.0, 2: 2.0, 3: 2.155, 4: 2.414, 5: 2.701, 6: 3.0}   # circumscribed circle of n equal circles


def draw_dia(wires, od_table):
    """{edge id: drawn tube diameter m}: bundle OD of the edge's largest row, capped at 6 mm (10 AWG pairs)."""
    od = dict((int(a), b) for a, b in od_table)
    out = {}
    for w in wires:
        d = min(0.006, od.get(int(w[2]), 1.0) * BUNDLE_K.get(int(w[3]), 3.0) / 1000.0)
        out[w[1]] = round(max(out.get(w[1], 0.0), d), 4)
    return dict(sorted(out.items()))


def _unit(v):
    n = math.sqrt(sum(c * c for c in v))
    return [c / n for c in v] if n > 1e-12 else None


def _cross(a, b):
    return [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]


def draw_strands(row, od_table, want_lat=False):
    """What the CAD draws for one wire row: [[diameter, polyline], ...].
    Rows with groove (G) runs whose conductors lie in separate grooves are drawn conductor by conductor: the 16 AWG
    pairs (+ and - in their own 3.0 mm grooves at 5 mm pitch, side by side 0.1 mm apart elsewhere) and the 26 AWG
    servo ribbon (3 x 1.1 mm side by side). Every other row is one bundle tube of its circumscribed diameter.
    Lateral direction per vertex: flat on the surface the run lies on (G, P, M: horizontal; B: in the fin face),
    carried over (projected) through free and liner runs. Points marked "s" or coded G use the groove spacing."""
    _wid, _eid, awg, n, _tw, _lay, _loop, _gpm, _f, pts = row
    od = dict((int(a), b) for a, b in od_table)
    d = od.get(int(awg), 1.0) / 1000.0
    fix = STRAND_FIX.get(row[0], lambda s: s)
    if not any(p[3] == "G" for p in pts) or (int(awg), int(n)) not in ((16, 2), (26, 3), (22, 3)):
        return fix([[round(min(0.006, d * BUNDLE_K.get(int(n), 3.0)), 5), [list(p[:3]) for p in pts]]])
    dias = None
    if int(awg) == 16:
        free, groove = [-(d / 2 + 0.00005), d / 2 + 0.00005], [-0.0025, 0.0025]
    elif int(awg) == 22:                    # servo lead: 28 AWG signal + 22 AWG + / -, packed 0.05 mm apart, centred
        dias = [v / 1000.0 for v in SRV_DIA_MM]
        w = sum(dias) + 0.0001
        o, acc = [], -w / 2
        for dd in dias:
            o.append(acc + dd / 2)
            acc += dd + 0.00005
        free = groove = o
    else:
        free = groove = [-(d + 0.00005), 0.0, d + 0.00005]
    P = [list(p[:3]) for p in pts]
    m = len(P)
    seg = [_unit([P[i + 1][k] - P[i][k] for k in range(3)]) for i in range(m - 1)]
    lat = [None] * m
    for i in range(m):
        a, b = seg[i - 1] if i > 0 else None, seg[i] if i < m - 1 else None
        t = _unit([(a[k] if a else 0) + (b[k] if b else 0) for k in range(3)]) or a or b
        code = pts[i][3] if i < m - 1 else pts[i - 1][3]
        nref = [0.0, 0.0, 1.0] if code in ("G", "P", "M", "L", "J") else [0.0, 1.0, 0.0] if code == "B" else None
        #      L (liners: fin grommet, P1 straw): conductors side by side across x, as in the grooves either side
        v = _unit(_cross(t, nref)) if nref else None
        if v is None or (nref and abs(sum(t[k] * nref[k] for k in range(3))) > 0.95):
            prev = next((lat[j] for j in range(i - 1, -1, -1) if lat[j]), None)
            if prev:
                dp = sum(prev[k] * t[k] for k in range(3))
                v = _unit([prev[k] - dp * t[k] for k in range(3)])
        if v and i > 0 and lat[i - 1] and sum(v[k] * lat[i - 1][k] for k in range(3)) < 0:
            v = [-c for c in v]
        lat[i] = v
    first = next((v for v in lat if v), [1.0, 0.0, 0.0])
    lat = [v or first for v in lat]
    for i in range(m - 1, 0, -1):                        # the leading vertices carry the first defined direction
        if sum(lat[i][k] * lat[i - 1][k] for k in range(3)) < 0:
            lat[i - 1] = [-c for c in lat[i - 1]]
    if want_lat:
        return lat
    # D-87: round the centre line at the row's bend radius FIRST, then offset each conductor from it, the lateral
    # direction and the spacing interpolated along the run: at a bend the inner conductor then turns on R - o and
    # the outer on R + o (concentric, as a real pair lies), instead of each conductor being rounded on its own at
    # the same R (which made the two cross at every bend in the bend plane)
    bar = [-0.003, 0.003]                                # D-87 "b": the two bus bars, 7 mm pitch, conductors 6 mm apart
    offs = [(bar if (len(p) > 4 and p[4] == "b") else groove if (p[3] == "G" or (len(p) > 4 and p[4] == "s"))
             else free) for p in pts]
    bend = dict((int(a), b) for a, b in BEND_K).get(int(awg), 3.0) * od.get(int(awg), 1.0) / 1000.0
    C0 = _fillet(P, bend)
    C = [C0[0]]
    for q in C0[1:-1]:                                   # thin near-duplicates (they made 0.1 mm zig-zags)
        if math.dist(q, C[-1]) >= 0.0003:
            C.append(q)
    if math.dist(C0[-1], C[-1]) < 0.0003 and len(C) > 1:
        C.pop()
    C.append(C0[-1])
    cum = [0.0]
    for i in range(m - 1):
        cum.append(cum[-1] + math.dist(P[i], P[i + 1]))
    k0, sc = 0, []
    for q in C:                                          # arc position of each rounded point on the polyline
        best = None
        for k in range(max(0, k0 - 1), min(m - 1, k0 + 3)):
            a_, b_ = P[k], P[k + 1]
            ab = [b_[c] - a_[c] for c in range(3)]
            L2 = sum(v * v for v in ab) or 1e-18
            t = max(0.0, min(1.0, sum((q[c] - a_[c]) * ab[c] for c in range(3)) / L2))
            dd = math.dist(q, [a_[c] + t * ab[c] for c in range(3)])
            if best is None or dd < best[0] - 1e-12:
                best = (dd, k, t)
        k0 = best[1]
        sc.append(cum[k0] + best[2] * (cum[k0 + 1] - cum[k0]))
    out = [[round(dias[j] if dias else d, 5), []] for j in range(len(free))]
    for n, q in enumerate(C):
        sv = sc[n]
        k = max(0, min(m - 2, next((i for i in range(m - 1) if cum[i + 1] >= sv), m - 2)))
        f = 0.0 if cum[k + 1] == cum[k] else (sv - cum[k]) / (cum[k + 1] - cum[k])
        f = f * f * (3 - 2 * f)                          # eased: no corner where the spacing or the lay changes
        lv = [lat[k][c] * (1 - f) + lat[k + 1][c] * f for c in range(3)]
        q0, q1 = C[max(n - 1, 0)], C[min(n + 1, len(C) - 1)]
        tg = _unit([q1[c] - q0[c] for c in range(3)]) or [1.0, 0.0, 0.0]
        dp = sum(lv[c] * tg[c] for c in range(3))
        lv = _unit([lv[c] - dp * tg[c] for c in range(3)]) or lat[k]
        for j in range(len(free)):
            o = offs[k][j] * (1 - f) + offs[k + 1][j] * f
            out[j][1].append([round(q[c] + lv[c] * o, 5) for c in range(3)])
    for s_ in out:                                       # drop points a straight run does not need (shape kept
        s_[1] = _simplify(s_[1], 0.00002)                # within 0.02 mm; the model stays small enough to publish)
    return fix(out)


# D-89 follow-up: lap-soldered ends (a conductor laid on a pad or bus bar) get a solder fillet that wraps the tip, so
# no drawn conductor shows a bare cut face: [row id, which end, part the joint is drawn on, flat (pad / bar top z)]
LAP_ENDS = ([["W-PWR-" + st, 0, "PWR-004", "bar"] for st in STATIONS] +
            [["W-MAIN-2", 0, "PWR-003", "pad"], ["W-MAIN-2", -1, "PWR-004", "bar", 0.0008], ["W-MAIN-1", -1, "PWR-003", "pad"],
             ["W-RX", -1, "AVN-003", "rx"]])
LAP_FLAT = {"bar": 0.0255, "pad": 0.0491, "rx": 0.0261}     # bar top (BAR_TOP), PDB pad joint top, RX pad joint top
LAP_LEN = {10: 0.0040, 16: 0.0018, 28: 0.0020}              # fillet length along the conductor, EST (16 AWG
#                                                            pairs rise 1.5 mm after the landing: the fillet ends first)
LAP_WALL = 0.0003                                            # solder at the conductor's sides, EST
LAP_TOP = 0.00018                                            # ... and over its top: the pairs pass 0.15 mm over the landings aft
#                                                            (0.03 mm contact, inside the gate's 0.05 mm)
SOLDER_RHO = 8.4                                             # g/cm3, Sn63Pb37, EST


def lap_joints(wires, od_table):
    """One D-shaped solder fillet per lap-soldered conductor end: along the conductor's (axis-aligned) end direction,
    from LAP_LEN behind the tip to 0.4 mm past it; section = circle r + LAP_WALL round the conductor, cut flat on the
    pad / bar top (it bonds there). Drawn by the part's own module (power.py, avionics.py) from cad.lap_joints."""
    rows = {w[0]: w for w in wires}
    out = []
    for wid, which, part, kind, *ln in LAP_ENDS:
        row = rows[wid]
        for k, (d, line) in enumerate(draw_strands(row, od_table)):
            if wid == "W-RX" and k == 0:
                continue                                    # the jacket ends in the breakout sleeve
            P = line if which == 0 else line[::-1]
            tip = P[0]
            prev = next(q for q in P[1:] if math.dist(q, tip) > 0.0008)
            t = [tip[c] - prev[c] for c in range(3)]
            ax = max(range(2), key=lambda c: abs(t[c]))     # horizontal axis the lap lies along
            sgn = 1 if t[ax] > 0 else -1
            u = 1 - ax                                      # the other horizontal coordinate
            L_ = ln[0] if ln else LAP_LEN.get(int(row[2]), 0.003)
            tilt0 = math.acos(min(1.0, abs(t[ax]) / math.sqrt(sum(c * c for c in t))))
            r = d / 2 + LAP_WALL + L_ * math.sin(tilt0) + (0.00025 if tilt0 > 0.05 else 0.0)  # slanted tip: room
            fz = LAP_FLAT[kind] - 0.0003                    # sunk 0.3 mm into its own pad / bar: the conductor's
            #                                                 whole section enters the fillet's end face
            uc, vc = tip[u], tip[2]
            h = max(-r, min(r, fz - vc))                    # flat level relative to the centre
            a0 = math.asin(h / r)
            n = 16
            # arc over the top, from the flat's right end round to its left end (the chord closes the loop)
            loop = [[uc + r * math.cos(a0 + (math.pi - 2 * a0) * i / n),
                     vc + r * math.sin(a0 + (math.pi - 2 * a0) * i / n)] for i in range(n + 1)]
            ztop = vc + d / 2 + LAP_TOP                    # flat top: thin solder over the conductor
            loop = [[q[0], min(q[1], ztop)] for q in loop]
            if len(ln) > 1:                                # clipped short of a neighbour (the RX ahead of the bars)
                loop = [[max(q[0], ln[1]), q[1]] for q in loop]
            loop = [q for i, q in enumerate(loop) if i == 0 or abs(q[0] - loop[i - 1][0]) + abs(q[1] - loop[i - 1][1]) > 1e-7]
            a_tip = tip[ax]
            tilt = math.acos(min(1.0, abs(t[ax]) / math.sqrt(sum(c * c for c in t))))
            over = 0.0004 + d / 2 * math.sin(tilt) + 0.0002 # past the tip: covers a tip that meets the pad at a slant
            a_lo, a_hi = sorted((a_tip + sgn * over, a_tip - sgn * (ln[0] if ln else LAP_LEN.get(int(row[2]), 0.003))))
            area = 0.5 * sum(loop[i][0] * loop[i - 1][1] - loop[i - 1][0] * loop[i][1] for i in range(len(loop)))
            vol = max(0.0, abs(area) - math.pi * (d / 2) ** 2) * (a_hi - a_lo)
            out.append({"part": part, "wire": row[1], "row": wid, "axis": "XY"[ax], "a": [round(a_lo, 6), round(a_hi, 6)],
                        "loop": [[round(q[0], 6), round(q[1], 6)] for q in loop], "mass_g": round(vol * SOLDER_RHO * 1e6, 4)})
    return out


def _simplify(pts, eps):
    """Douglas-Peucker on a 3-D polyline: keeps every point that deviates more than eps from its chord."""
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        i, j = stack.pop()
        a, b = pts[i], pts[j]
        ab = [b[c] - a[c] for c in range(3)]
        L2 = sum(v * v for v in ab) or 1e-18
        best, idx = 0.0, None
        for k in range(i + 1, j):
            t = max(0.0, min(1.0, sum((pts[k][c] - a[c]) * ab[c] for c in range(3)) / L2))
            d = math.dist(pts[k], [a[c] + t * ab[c] for c in range(3)])
            if d > best:
                best, idx = d, k
        if idx is not None and best > eps:
            keep[idx] = True
            stack += [(i, idx), (idx, j)]
    return [p for p, k in zip(pts, keep) if k]


def _fillet_r(points, radii, steps=6):
    """_fillet with its own radius at each inner corner (radii[i] at points[i + 1])."""
    P = [list(p) for p in points]
    out = [P[0]]
    for i in range(1, len(P) - 1):
        seg = _fillet([P[i - 1], P[i], P[i + 1]], radii[i - 1], steps)
        out += seg[1:-1]
    out.append(P[-1])
    return out


def _fillet(points, radius, steps=6):
    """blender_backend.fillet_polyline in plain Python: the bend the 3-D model draws at each corner."""
    P = [list(p) for p in points]
    if len(P) < 3 or radius <= 0:
        return P
    out = [P[0]]
    for i in range(1, len(P) - 1):
        a, b, c = P[i - 1], P[i], P[i + 1]
        d1, d2 = [b[k] - a[k] for k in range(3)], [c[k] - b[k] for k in range(3)]
        n1, n2 = math.hypot(*d1), math.hypot(*d2)
        if n1 < 1e-9 or n2 < 1e-9:
            continue
        ang = math.acos(max(-1.0, min(1.0, sum(d1[k] * d2[k] for k in range(3)) / n1 / n2)))
        if ang < 1e-3:
            out.append(b)
            continue
        t = min(radius * math.tan(ang / 2), 0.45 * n1, 0.45 * n2)
        A = [b[k] - d1[k] / n1 * t for k in range(3)]
        B = [b[k] + d2[k] / n2 * t for k in range(3)]
        n = max(1, min(steps, int(math.ceil(ang / 0.17))))   # as blender_backend.fillet_polyline (D-87)
        for q in range(n + 1):
            u = q / n
            out.append([(1 - u) ** 2 * A[k] + 2 * (1 - u) * u * b[k] + u * u * B[k] for k in range(3)])
    out.append(P[-1])
    return out


def skin_slots(g, wires, od_table):
    """D-86: where a drawn lead passes the tape skin (WNG-003, 0.1 mm on the core), the tape is slit round it, as it
    is on the bench: the lead is laid first and the tape is cut where the lead comes out. [x0, x1, y0, y1, side] per
    crossing, merged, from every drawn strand (filleted as the 3-D model draws it), outboard of the pod side walls."""
    t, step = 0.0001, 0.0005
    odd = dict((int(a), b) for a, b in od_table)
    raw = []
    for w in wires:
        bend = dict((int(a), b) for a, b in BEND_K).get(int(w[2]), 3.0) * odd.get(int(w[2]), 1.0) / 1000.0
        for d, line in draw_strands(w, od_table):
            pts, r = _fillet(line, bend), d / 2
            samples = []
            for a, b in zip(pts, pts[1:]):
                n = max(1, int(math.dist(a, b) / step))
                samples += [[a[k] + (b[k] - a[k]) * i / n for k in range(3)] for i in range(n)]
            samples.append(pts[-1])
            for side, surf, sgn in (("upper", g["zU"], 1.0), ("lower", g["zL"], -1.0)):
                run = []
                for x, y, z in samples + [[None] * 3]:
                    hit = x is not None and 0.0 <= x <= g["c"] and g["pod_hw"] + 0.0005 <= abs(y) <= g["half"] and \
                        -r + 0.0004 < sgn * (z - surf(x)) < r + t + 0.0004
                    if hit:
                        run.append((x, y))
                    elif run:
                        e = r + 0.0015
                        raw.append([min(p[0] for p in run) - e, max(p[0] for p in run) + e,
                                    min(p[1] for p in run) - e, max(p[1] for p in run) + e, side])
                        run = []
    merged = []
    for s in sorted(raw):
        for m in merged:
            if m[4] == s[4] and s[0] <= m[1] and m[0] <= s[1] and s[2] <= m[3] and m[2] <= s[3]:
                m[0], m[1], m[2], m[3] = min(m[0], s[0]), max(m[1], s[1]), min(m[2], s[2]), max(m[3], s[3])
                break
        else:
            merged.append(list(s))
    return [[round(v, 4) for v in m[:4]] + [m[4]] for m in merged]


