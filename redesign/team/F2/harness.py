def load_json(p):
    return json.loads(Path(p).read_text(encoding="utf-8"))


def pv(d, key):
    cur = d
    for k in key.split("."):
        cur = cur[k]
    return cur["value"] if isinstance(cur, dict) and "value" in cur else cur


def airfoil(path, chord):
    pts = []
    for line in Path(path).read_text().splitlines()[1:]:
        s = line.split()
        if len(s) == 2:
            pts.append((float(s[0]), float(s[1])))
    i = min(range(len(pts)), key=lambda k: pts[k][0])
    up, lo = pts[:i + 1][::-1], pts[i:]

    def z(surf, x):
        u = x / chord
        for a, b in zip(surf, surf[1:]):
            if a[0] <= u <= b[0]:
                return chord * (a[1] + (u - a[0]) / (b[0] - a[0]) * (b[1] - a[1]))
        return 0.0
    return (lambda x: z(up, x)), (lambda x: z(lo, x))


