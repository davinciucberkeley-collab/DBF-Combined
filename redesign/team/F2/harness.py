@kit.calc("CALC-F2-LENGTHS", title="Routed cut lengths per wire (path x helix + service loop)",
          equation="L_cut = sum(seg x helix(OD, lay) if twisted) + loop; helix = sqrt(1 + (pi OD / lay)^2)",
          inputs={"wires": "P:harness.wire_table", "od": "P:harness.wire_od_mm"},
          units={"od": "AWG,mm"}, output="esc_max")
def calc_lengths(wires, od):
    return lengths(wires, od)


@kit.calc("CALC-F2-PHASE-EXT", title="Phase extension = routed reach - factory motor lead - factory ESC lead",
          equation="ext = max(0, reach - L_motor - L_esc)",
          inputs={"reach": "CL-F2-PHASE-REACH", "leads": "ASM-F2-FACTORY-LEADS"}, output="ext")
def calc_phase_ext(reach, leads):
    return {"ext": max(0.0, reach - leads[0] - leads[1])}


@kit.calc("CALC-F2-MASS", title="Harness mass and CG (wire g/m x routed length + fittings at their stations)",
          equation="m = sum(gpm n L_supplied) + sum(fittings); CG = sum(m_i r_i) / m",
          inputs={"wires": "P:harness.wire_table", "od": "P:harness.wire_od_mm",
                  "fittings": "P:harness.fittings_table", "pod_box": "P:harness.pod_box"},
          units={"od": "AWG,mm"}, output="mass_g")
def calc_mass(wires, od, fittings, pod_box):
    m, cg, parts = mass_cg(wires, od, fittings, pod_box)
    return {"mass_g": m, "cg_x": cg[0], "cg_y": cg[1], "cg_z": cg[2],
            "pod_g": parts["HRN-001"]["mass_g"], "side_g": parts["HRN-002-R"]["mass_g"]}


@kit.calc("CALC-F2-INSTALL", title="Installation geometry: bends, free spans, groove-to-mast distance",
          equation="r_max = min(tangent room) / tan(theta/2) >= k OD; free span; min |p - GPS|",
          inputs={"wires": "P:harness.wire_table", "od": "P:harness.wire_od_mm", "k": "P:harness.rules.bend_k",
                  "gps": "P:harness.ref.gps_top_xyz_m"},
          units={"od": "AWG,mm", "k": "AWG,-", "gps": "m"}, output="bend_ratio")
def calc_install(wires, od, k, gps):
    return {"bend_ratio": bends(wires, od, k)[0], "free_span": free_span(wires), "mast_clear": mast_clear(wires, gps)}


@kit.calc("CALC-F2-FILL", title="Fill of every pass (exits, crossing, straws, grommets)",
          equation="fill = sum(pi/4 OD_i^2) / opening area",
          inputs={"passes": "P:harness.passes", "od": "P:harness.wire_od_mm"}, units={"od": "AWG,mm"},
          output="fill_max")
def calc_fill(passes, od):
    odd = dict((int(a), b) for a, b in od)
    worst = 0.0
    for _name, area_mm2, contents in passes:
        a = sum(n * math.pi / 4 * odd[int(awg)] ** 2 for awg, n in contents)
        worst = max(worst, a / area_mm2)
    return {"fill_max": worst}


@kit.calc("CALC-F2-SERVO-V", title="Servo terminal voltage with both servos stalled",
          equation="V = V_ubec - I_stall (2 L R'_26AWG + n_contacts R_c)",
          inputs={"L": "CL-F2-SERVO-LEN", "I": "ASM-F1-SERVO-STALL", "elec": "ASM-F2-SERVO-CIRCUIT"},
          units={"L": "m", "I": "A"}, output="v_servo")
def calc_servo_v(L, I, elec):
    v_ubec, r_per_m, n_contacts, r_contact = elec
    return {"v_servo": v_ubec - I * (2 * L * r_per_m + n_contacts * r_contact)}


@kit.calc("CALC-F2-BODIES", title="CAD bundle legs sized by the wire mass they carry; body centroid vs wire-mass CG",
          equation="d_leg = sqrt(4 m_leg / (pi L_leg rho)); cg_body = sum(d^2 L r_mid) / sum(d^2 L); gap = |cg_body - cg_wire|",
          inputs={"wires": "P:harness.wire_table", "od": "P:harness.wire_od_mm",
                  "fittings": "P:harness.fittings_table", "pod_box": "P:harness.pod_box",
                  "legs": "P:harness.cad.bundle_legs"},
          units={"od": "AWG,mm"}, output="cg_gap_max")
def calc_bodies(wires, od, fittings, pod_box, legs):
    r = bodies(wires, od, fittings, pod_box, legs)
    return {"cg_gap_max": r["cg_gap_max"], "gap_pod": r["gap"]["HRN-001"], "gap_side": r["gap"]["HRN-002-R"]}


