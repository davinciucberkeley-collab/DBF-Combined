"""Build the in-page proof chain (the #proof page of app.html) from the standalone viewer in site/proofs/index.html.

    python -I redesign/site/make_proof_embed.py     # then: python -I redesign/site/make_index.py

Stdlib only, deterministic. Writes
  - site/proofs/embed.css : the viewer's own CSS (not its tokens, which site.css already has), every selector scoped under
                            #proofapp so it cannot touch the rest of the page;
  - the markup between the `proof-embed:` marker comments in app.html: the viewer's DOM, with the page-level pieces
    changed (the <main> becomes .pmain, the theme button goes, a Back / Close pair is added).
site/proofs/app.js runs unchanged in both places: with window.PROOF_EMBED set (site.js does this) it works inside #proofapp
and routes by the plain hashes #proof, #proof-overview and #proof-<node id>.
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'proofs', 'index.html')
CSS_OUT = os.path.join(HERE, 'proofs', 'embed.css')
APP = os.path.join(HERE, 'app.html')
BEGIN = '<!-- proof-embed:begin (generated by redesign/site/make_proof_embed.py from site/proofs/index.html; do not edit) -->'
END = '<!-- proof-embed:end -->'
ROOT = '#proofapp'


def scope(css):
    out = []
    i, n = 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0:
            break
        sel = css[i:j].strip()
        depth, k = 1, j + 1
        while depth:
            depth += {'{': 1, '}': -1}.get(css[k], 0)
            k += 1
        body = css[j + 1:k - 1]
        i = k
        if sel.startswith('@media'):
            out.append('%s {\n%s}\n' % (sel, scope(body)))
            continue
        sels = []
        for s in (x.strip() for x in sel.split(',')):
            if s in ('html', 'body', 'html, body') or s.startswith(('html ', 'body ')):
                continue                                   # page-level rules belong to the site
            s = re.sub(r'^main\b', '.pmain', s)
            sels.append(ROOT + ' ' + s)
        if sels:
            out.append('%s {%s}\n' % (',\n'.join(sels), body.strip() and ' ' + ' '.join(body.split()) + ' '))
    return ''.join(out)


def main():
    with open(SRC, encoding='utf-8') as f:
        src = f.read().replace('\r\n', '\n')
    style = re.search(r'<style>(.*?)</style>', src, re.S).group(1)
    style = style[style.index('[data-status="UNVERIFIED"]'):]            # drop the :root token blocks: site.css has them
    style = re.sub(r'/\*.*?\*/', '', style, flags=re.S)
    style = style.replace('height: 100vh;', 'height: calc(100vh - var(--topbar-h) - env(safe-area-inset-top, 0px));')
    css = ('/* generated by redesign/site/make_proof_embed.py from site/proofs/index.html; do not edit */\n'
           + scope(style)
           + '/* page glue: the proof chain sits inside the site\'s own page frame */\n'
           + ROOT + ' { display: block; }\n'
           + ROOT + ' .phead-back { display: inline-flex; gap: 8px; align-items: center; }\n'
           + ROOT + ' .home .sub { background: none; border: 0; padding: 0; border-radius: 0; box-shadow: none; display: block; }\n'
           + ROOT + ' .partbtn { text-decoration: none; }\n')
    with open(CSS_OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(css)

    m = re.search(r'<div class="app" id="app">\n(.*?)\n</div>\n\n<script src="model.js">', src, re.S)
    dom = m.group(1)
    dom = re.sub(r'\s*<button class="iconbtn" id="theme"[^>]*>.*?</button>', '', dom)
    dom = dom.replace(' id="legend"', '').replace(' id="hint"', '')            # the explorer page owns those ids
    dom = dom.replace('<main>', '<div class="pmain">').replace('</main>', '</div>')
    dom = dom.replace('<div class="brand"><b>Proof chains</b>',
                      '<div class="phead-back"><button class="btn" type="button" data-pback title="Back to where you came from">&larr; Back</button></div>\n'
                      '    <div class="brand"><b>Proof chains</b>')
    dom = dom.replace('<div class="spacer"></div>', '<div class="spacer"></div>', 1)
    dom = dom.replace('</div>\n  </header>', '</div>\n    <button class="btn" type="button" data-pclose title="Close the proof chain">Close &times;</button>\n  </header>', 1)
    block = ('%s\n<section class="view" id="proof" hidden>\n'
             '<div id="proofapp">\n<div class="app">\n%s\n</div>\n</div>\n</section>\n%s' % (BEGIN, dom, END))
    with open(APP, encoding='utf-8', newline='') as f:
        s = f.read()
    nl = '\r\n' if '\r\n' in s else '\n'
    block = block.replace('\n', nl)
    a, b = s.find('<!-- proof-embed:begin'), s.find(END)
    if a < 0 or b < 0:
        raise SystemExit('app.html has no proof-embed markers')
    new = s[:a] + block + s[b + len(END):]
    if new != s:
        with open(APP, 'w', encoding='utf-8', newline='') as f:
            f.write(new)
    print('proof embed: embed.css %d bytes, app.html %s' % (len(css), 'updated' if new != s else 'unchanged'))


main()
