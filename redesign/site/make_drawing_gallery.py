"""make_drawing_gallery.py - put the concept A engineering drawings into the Explorer.

Reads the first sheet of every drawing (qp/A/drawings/out/<id>.png, written by qp/A/drawings/compose_drawings.py) and writes
  site/assets/drawings/<id>.webp        full sheet for the lightbox (white background)
  site/assets/drawings/thumb/<id>.jpg   480 px wide thumbnail
and the gallery block between <!-- drawings:begin --> and <!-- drawings:end --> in site/app.html (Build guide page), with the
parts, material and size from qp/A/drawings/out/DRAWINGS-A.md and part names from site/data/viewer-data.json.
The part panel of the 3-D viewer (viewer.js) shows the same sheet for each made part. Re-run after make_drawings_a.py, then make_index.py.
"""
import html
import json
import os
import re

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), 'qp', 'A', 'drawings', 'out')
DST = os.path.join(HERE, 'assets', 'drawings')
GH = 'https://github.com/davinciucberkeley-collab/DBF-Combined/blob/redesign/v1/redesign/qp/A/drawings/out/'


def rows():
    """(id, parts, qty, material, size, sheets) from the DRAWINGS-A.md drawing table, in its order."""
    r = []
    for line in open(os.path.join(OUT, 'DRAWINGS-A.md'), encoding='utf-8'):
        m = re.match(r'\| \[([A-Z0-9-]+)\]\([^)]*\.pdf\) \| (.*?) \((\d+)\) \| (.*?) \| (.*?) \| (.*?) \|$', line.strip())
        if m:
            r.append(m.groups())
    return r


def main():
    os.makedirs(os.path.join(DST, 'thumb'), exist_ok=True)
    names = {p['id']: p.get('name') or '' for p in json.load(open(os.path.join(HERE, 'data', 'viewer-data.json'), encoding='utf-8'))['parts']}
    figs, total = [], 0
    for did, parts, qty, mat, size, sheets in rows():
        png = os.path.join(OUT, did + '.png')
        if not os.path.exists(png):
            print('no sheet image for %s' % did)
            continue
        im = Image.open(png)
        bg = Image.new('RGB', im.size, (255, 255, 255))
        bg.paste(im, mask=im.split()[-1] if im.mode == 'RGBA' else None)
        full = os.path.join(DST, did + '.webp')
        bg.save(full, 'WEBP', quality=88, method=6)
        th = bg.copy()
        th.thumbnail((480, 480), Image.LANCZOS)
        th.save(os.path.join(DST, 'thumb', did + '.jpg'), 'JPEG', quality=85, optimize=True)
        total += os.path.getsize(full)
        first = parts.split(',')[0].strip()
        name = names.get(first) or names.get(did) or ''
        name = re.split(r' \(|: ', name)[0].strip()               # the short name; the full one is in the part panel
        name = name if len(name) <= 48 else name[:47].rstrip() + '...'
        nsh = re.match(r'(\d+)', sheets)
        more = int(nsh.group(1)) - 1 if nsh else 0
        cap = '%s%s: %s (qty %s), %s, %s mm.%s' % (did, (' ' + name) if name else '', parts, qty, mat, size,
                                                   (' Sheet 1 of %d; the PDF has the rest.' % (more + 1)) if more else '')
        c = html.escape(cap, quote=True)
        figs.append('<figure class="shot drw" id="drw-%s"><a href="assets/drawings/%s.webp" data-lightbox="assets/drawings/%s.webp" data-caption="%s">'
                    '<img src="assets/drawings/thumb/%s.jpg" alt="Engineering drawing %s" loading="lazy" width="%d" height="%d"></a>'
                    '<figcaption><b>%s</b> %s<br><span class="ds-meta">%s &middot; qty %s &middot; %s mm &middot; <a class="ds-link" href="%s%s.pdf" target="_blank" rel="noopener">PDF</a></span></figcaption></figure>'
                    % (did, did, did, c, did, html.escape(did), th.size[0], th.size[1], html.escape(did), html.escape(name),
                       html.escape(mat), qty, html.escape(size), GH, did))
    block = ('<!-- drawings:begin (generated by redesign/site/make_drawing_gallery.py; do not edit) -->\n'
             '<details class="md-step drw-set" id="build-drawings" open><summary><h3 class="md-h3">Engineering drawings: %d sheets (click a sheet to enlarge)</h3></summary>\n'
             '<p class="ds-meta">First sheet of each drawing, from the CAD (qp/A/drawings/make_drawings_a.py). Parts with two sheets have the feature table continued in the PDF. '
             'In the 3-D viewer, click a made part to see its own sheet.</p>\n'
             '<div class="gallery drw-gallery">%s</div>\n</details>\n<!-- drawings:end -->' % (len(figs), ''.join(figs)))
    app = os.path.join(HERE, 'app.html')
    s = open(app, encoding='utf-8').read()
    if '<!-- drawings:begin' in s:
        s = re.sub(r'<!-- drawings:begin.*?<!-- drawings:end -->', lambda m: block, s, flags=re.S)
    else:
        anchor = '<!-- build-guide:begin'
        i = s.index(anchor)
        s = s[:i] + block + '\n' + s[i:]
    open(app, 'w', encoding='utf-8', newline='\n').write(s)
    print('drawing gallery: %d sheets, %.1f MB of full-size WebP' % (len(figs), total / 1e6))


main()
