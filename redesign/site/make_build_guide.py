"""Render redesign/BUILD-GUIDE.md into the in-site build guide (the #build page of app.html).

    python -I redesign/site/make_build_guide.py     # then: python -I redesign/site/make_index.py

Stdlib only, deterministic (no timestamps): re-running with no change to BUILD-GUIDE.md writes the same bytes.
The text between the two `build-guide:` marker comments in app.html is replaced; everything outside them is hand-written.

What it does with the Markdown:
  - headings (ids `build-<slug>`; stage N gets `build-stage-N`), paragraphs, lists (nested), tables, code, rules;
  - each `## Stage N.` section (N = 2..11) gets its clip, assets/animation/build/stage-NN.mp4 with the stage-NN.png poster,
    straight after the heading; the guide's own "[![..](stage-NN.png)](stage-NN.mp4)" / "Play the clip" lines are dropped;
  - images under showcase/renders/ point at assets/renders/ and open in the page lightbox; images and clip posters carry
    data-src / data-poster and site.js fills them in when the guide is first opened (about 10 MB stays off the first load); an image that has no copy in
    the site (review/img/...) becomes a link to the file on GitHub;
  - any other relative link (subsystems/*/BUILD.md, review/*.md, team/**) becomes a GitHub link, as the site does elsewhere.
"""
import html, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'BUILD-GUIDE.md')
APP = os.path.join(HERE, 'app.html')
GH = 'https://github.com/davinciucberkeley-collab/DBF-Combined/blob/redesign/v1/redesign/'
BEGIN = '<!-- build-guide:begin (generated by redesign/site/make_build_guide.py from redesign/BUILD-GUIDE.md; do not edit) -->'
END = '<!-- build-guide:end -->'
STAGE_TITLE_VIDEOS = range(2, 12)


def esc(s):
    return html.escape(s, quote=True)


def slug(text):
    s = re.sub(r'[^a-z0-9]+', '-', re.sub(r'<[^>]+>', '', text).lower()).strip('-')
    return s or 'section'


def site_asset(path):
    """Site-relative path for a repo path under showcase/, or None when the site carries no copy."""
    for src, dst in (('showcase/renders/', 'assets/renders/'), ('showcase/animation/build/', 'assets/animation/build/')):
        if path.startswith(src) and os.path.exists(os.path.join(HERE, dst + path[len(src):])):
            return dst + path[len(src):]
    return None


def href_for(url):
    url = url.strip()
    if re.match(r'https?://', url):
        return url, True
    if url.startswith('#'):
        return url, False                                  # in-page anchor
    path = url.split('#')[0]
    if path.endswith('k09l-build.mp4'):
        return '#how-its-built', False                     # the whole-build animation figure
    if site_asset(path):
        return site_asset(path), False
    return GH + url, True


def inline(text):
    codes = []

    def keep(m):
        codes.append('<code>' + esc(m.group(1)) + '</code>')
        return '\x00%d\x00' % (len(codes) - 1)
    t = re.sub(r'`([^`]+)`', keep, text)
    t = esc(t)

    def img(m):
        alt, src = m.group(1), html.unescape(m.group(2))
        local = site_asset(src)
        if not local:
            return '<a class="ds-link" href="%s" target="_blank" rel="noopener">%s (figure on GitHub)</a>' % (esc(GH + src), alt)
        return '<a class="md-img" href="%s" data-lightbox="%s" data-caption="%s"><img data-src="%s" alt="%s"></a>' % (
            local, local, alt, local, alt)
    t = re.sub(r'!\[([^\]]*)\]\(([^)\s]+)\)', img, t)

    def link(m):
        h, ext = href_for(html.unescape(m.group(2)))
        return '<a class="ds-link" href="%s"%s>%s</a>' % (esc(h), ' target="_blank" rel="noopener"' if ext else '', m.group(1))
    t = re.sub(r'\[([^\]]+)\]\(([^)\s]+)\)', link, t)
    t = re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', t)
    t = re.sub(r'(?<![\*\w])\*(?!\s)([^*]+?)(?<!\s)\*(?![\*\w])', r'<em>\1</em>', t)
    return re.sub(r'\x00(\d+)\x00', lambda m: codes[int(m.group(1))], t)


LIST_RE = re.compile(r'^(\s*)([-*]|\d+\.)\s+(.*)$')
LABEL_RE = re.compile(r'^[A-Z][A-Za-z ]{1,18}:\s')


def parse_list(lines, i, indent):
    """Parse a list whose markers sit at `indent`; returns (html, next index)."""
    m = LIST_RE.match(lines[i])
    ordered = m.group(2)[0].isdigit()
    items = []
    while i < len(lines):
        m = LIST_RE.match(lines[i])
        if not m or len(m.group(1)) != indent:
            break
        body = [m.group(3)]
        sub = ''
        i += 1
        while i < len(lines):
            ln = lines[i]
            if not ln.strip():
                break
            lm = LIST_RE.match(ln)
            if lm and len(lm.group(1)) == indent:
                break
            if lm and len(lm.group(1)) > indent:
                sub, i = parse_list(lines, i, len(lm.group(1)))
                continue
            if len(ln) - len(ln.lstrip()) <= indent:
                break
            body.append(ln.strip())
            i += 1
        items.append('<li>' + inline(' '.join(body)) + sub + '</li>')
    tag = 'ol' if ordered else 'ul'
    return '<%s>%s</%s>' % (tag, ''.join(items), tag), i


def cells(row):
    return [c.strip() for c in row.strip().strip('|').split('|')]


def table(rows):
    head = cells(rows[0])
    body = [cells(r) for r in rows[2:]]
    aligns = ['num' if re.match(r'^-+:$', c.strip()) else '' for c in cells(rows[1])]
    blank = not any(head)
    out = ['<div class="scroll fit"><table class="ds-table%s">' % (' md-figtable' if blank else '')]
    if not blank:
        out.append('<thead><tr>' + ''.join('<th>%s</th>' % inline(c) for c in head) + '</tr></thead>')
    out.append('<tbody>' + ''.join('<tr>' + ''.join('<td%s>%s</td>' % (' class="num"' if aligns[k:k + 1] == ['num'] else '', inline(c))
                                                  for k, c in enumerate(r)) + '</tr>' for r in body) + '</tbody></table></div>')
    return ''.join(out)


def stage_video(n):
    nn = '%02d' % n
    return ('<figure class="md-clip" id="build-clip-%d"><video src="assets/animation/build/stage-%s.mp4" data-poster="assets/animation/build/stage-%s.png" '
            'controls muted playsinline preload="none" aria-label="Stage %d build clip"></video>'
            '<figcaption><span class="ds-source">Stage %d clip · assets/animation/build/stage-%s.mp4 · same CAD as the collision check</span></figcaption></figure>'
            % (n, nn, nn, n, n, nn))


def render(md):
    lines = md.split('\n')
    out, toc, i = [], [], 0
    stage = None
    open_section = False
    title = 'Build guide'
    while i < len(lines):
        ln = lines[i]
        if not ln.strip():
            i += 1
            continue
        if ln.startswith('```'):
            j = i + 1
            while j < len(lines) and not lines[j].startswith('```'):
                j += 1
            out.append('<pre class="ds-code"><code>%s</code></pre>' % esc('\n'.join(lines[i + 1:j])))
            i = j + 1
            continue
        h = re.match(r'^(#{1,6})\s+(.*)$', ln)
        if h:
            level, text = len(h.group(1)), h.group(2).strip()
            if level == 1:
                title = text
                i += 1
                continue
            sm = re.match(r'^Stage (\d+)\.\s*(.*)$', text) if level == 2 else None
            hid = 'build-stage-%s' % sm.group(1) if sm else 'build-' + slug(text)
            if level == 2:
                if open_section:
                    out.append('</section>')
                out.append('<section class="md-sec" id="%s">' % hid)
                open_section = True
                toc.append((hid, text, sm.group(1) if sm else None))
            out.append('<h%d class="md-h%d">%s</h%d>' % (level, level, inline(text), level))
            stage = int(sm.group(1)) if sm else (None if level == 2 else stage)
            if stage in STAGE_TITLE_VIDEOS and level == 2:
                out.append(stage_video(stage))
            i += 1
            continue
        if re.match(r'^-{3,}\s*$', ln):
            i += 1
            continue
        if ln.lstrip().startswith('|') and i + 1 < len(lines) and re.match(r'^\s*\|[\s:|-]+\|\s*$', lines[i + 1]):
            j = i
            while j < len(lines) and lines[j].lstrip().startswith('|'):
                j += 1
            out.append(table(lines[i:j]))
            i = j
            continue
        if LIST_RE.match(ln):
            ul, i = parse_list(lines, i, len(LIST_RE.match(ln).group(1)))
            out.append(ul)
            continue
        # paragraph: consecutive non-blank lines that start no other block
        j = i
        while j < len(lines) and lines[j].strip() and not lines[j].startswith(('```', '#')) and not LIST_RE.match(lines[j]) \
                and not lines[j].lstrip().startswith('|'):
            j += 1
        para = [p.strip() for p in lines[i:j]]
        i = j
        if stage in STAGE_TITLE_VIDEOS and all(re.match(r'^(\[!\[Stage \d+ end state\]|\[Play the stage \d+ clip\])', p) for p in para):
            continue                                       # replaced by the embedded clip
        if len(para) == 1 and re.match(r'^!\[[^\]]*\]\([^)]+\)$', para[0]):
            out.append('<figure class="md-fig">%s<figcaption>%s</figcaption></figure>' % (inline(para[0]), esc(re.match(r'^!\[([^\]]*)\]', para[0]).group(1))))
            continue
        # a line that starts "Time:", "Parts:", "Detail:" ... stays on its own line
        chunks = [[para[0]]]
        for p in para[1:]:
            (chunks.append([p]) if LABEL_RE.match(p) else chunks[-1].append(p))
        cls = ' class="md-meta"' if stage in STAGE_TITLE_VIDEOS and LABEL_RE.match(para[0]) else ''
        out.append('<p%s>%s</p>' % (cls, '<br>'.join(inline(' '.join(c)) for c in chunks)))
    if open_section:
        out.append('</section>')
    return title, toc, '\n'.join(out)


def main():
    with open(SRC, encoding='utf-8') as f:
        md = f.read().replace('\r\n', '\n')
    title, toc, body = render(md)
    nav = '<nav class="md-toc" aria-label="Build guide sections">%s</nav>' % ''.join(
        '<a href="#%s"%s>%s</a>' % (hid, ' data-stage="%s"' % n if n else '', esc(re.sub(r'^Stage (\d+)\.\s*', r'\1 · ', t)))
        for hid, t, n in toc)
    block = '%s\n<div class="md-wrap">%s\n<article class="md">\n%s\n</article></div>\n%s' % (BEGIN, nav, body, END)
    with open(APP, encoding='utf-8', newline='') as f:
        s = f.read()
    block = block.replace('\n', '\r\n' if '\r\n' in s else '\n')
    a, b = s.find('<!-- build-guide:begin'), s.find(END)
    if a < 0 or b < 0:
        raise SystemExit('app.html has no build-guide markers (%s ... %s)' % (BEGIN[:22], END))
    new = s[:a] + block + s[b + len(END):]
    if new != s:
        with open(APP, 'w', encoding='utf-8', newline='') as f:
            f.write(new)
    print('build guide: %d sections, %d bytes of HTML, app.html %s' % (len(toc), len(body), 'updated' if new != s else 'unchanged'))


main()
