"""T-076d step 2 report: reads step2_rows.json (t076d_step2_table.py), writes step2_table.md, step2_choice.json.  python -I t076d_step2_report.py
Selection rule for the pad point used downstream (D-1, FE): among the grid points (CAD mass, maturity placement) that meet, at EVERY zeta of the grid (0.02 / 0.05 / 0.10, because the rate term is unmeasured, D-222 LR-1):
stroke reserve >= 2 mm, end tilt <= 3.0 deg (AR-008; 2.8 deg preferred, D-222 s4.1), n <= 12 g (A-P5) on the 21 cases and reserve >= 0 on the drift-0.70 cases, take the one with the smallest worst-over-zeta sleeve-exit moment.
The stop rule (D-222 s4.3 item 2) is evaluated at zeta 0.05: stop if no grid point meets reserve >= 2 mm, tilt <= 3.0, n <= 12."""
import os, sys, json, math
HERE = os.path.dirname(os.path.abspath(__file__))
rows = json.load(open(os.path.join(HERE, 'step2_rows.json')))
# 21 cases = those that appear in the baseline sims but are not drift .7
D = {}
for r in rows: D.setdefault((r['model'], r['Fp'], r['smax'], r['zeta']), []).append(r)
case21 = sorted({r['case'] for r in rows if '.7' not in r['case']}, key=lambda x: [r['case'] for r in rows].index(x))
cg_x, cg_z = 0.021433, 0.006369            # CAD CG (cad_mass.py now: 21.43 mm, 6.37 mm) used only for the A-P9 numbers below
import_cache = {}


def pad_geom(s_max):
    xf0, zf0 = 0.3415, 0.189
    if abs(s_max - 0.020) < 1e-9: return xf0, zf0
    x = xf0 + 1.5 * (s_max - 0.020); edge = math.tan(math.radians(30.5)) * (x - cg_x) + cg_z
    return x, edge - 0.006


def summ(rs):
    r21 = [r for r in rs if r['case'] in case21]; r70 = [r for r in rs if r['case'] not in case21]
    e = {q: max(r[q] for r in r21) for q in ('Mz_arm', 'M_arm', 'F_arm', 'Mexit', 'sigma', 'tau', 'stroke', 'tilt', 'n', 'Ffoot')}
    e['gov'] = max(r21, key=lambda r: r['Mexit'])['case']; s = rs[0]['smax'] * 1e3; e['smax'] = s; e['reserve'] = s - e['stroke']
    e['reserve70'] = min(s - r['stroke'] for r in r70); e['Mexit70'] = max(r['Mexit'] for r in r70); e['Mz70'] = max(r['Mz_arm'] for r in r70)
    e['stroke70'] = max(r['stroke'] for r in r70)
    return e


S = {k: summ(v) for k, v in D.items()}
L = []; P = L.append
P('# T-076d step 2: landing demand table (rigid-body dynamics + hand-calculation proxies; generated by t076d_step2_report.py from step2_rows.json)\n')
P('Models: **items** = old landing_a.ITEMS roll-up scaled to 1.64 kg (every lump x 1.290); **cad** = landing_mass_cad.py, maturity placement; **cad_E** = growth on class E only (sensitivity bracket).  1.64 kg, 21 cases (max over cases) + 3 drift-0.70 cases (separate columns).  Pad geometry follows the stroke (A-P9 held 30.5 deg).  Columns: arm-group Mz and |M| about P0 (N m), sleeve-exit moment proxy (N m, s = 25 mm), beam sigma / tau at s = 25 mm (MPa; RF at x1.5 = 350 / (1.725 x 1.5 x sigma), tau 30 / (1.725 x 1.5 x tau)), worst stroke (mm), reserve (usable - worst), end tilt (deg), peak n (g), peak foot force (N).\n')
for model in ('items', 'cad', 'cad_E'):
    P('\n## Model %s\n' % model)
    P('| Fp N | stroke mm | zeta | Mz_arm | M_arm | Mexit | sigma | tau | stroke | reserve | tilt | n | Ffoot | gov case (Mexit) | drift .7: reserve / Mexit |')
    P('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
    ks = sorted(k for k in S if k[0] == model)
    for k in ks:
        e = S[k]; base = (k[1] == 30.0 and abs(k[2] - 0.020) < 1e-9)
        P('| %s%.0f | %.0f | %.2f | %.2f | %.2f | %.2f | %.1f | %.2f | %.1f | %.1f | %.2f | %.2f | %.1f | %s | %.1f / %.2f |' % ('**' if base else '', k[1], k[2] * 1e3, k[3], e['Mz_arm'], e['M_arm'], e['Mexit'], e['sigma'], e['tau'], e['stroke'], e['reserve'], e['tilt'], e['n'], e['Ffoot'], e['gov'], e['reserve70'], e['Mexit70']))
    P('')
P('\n(bold Fp = baseline 30 N / 20 mm rows; all other rows have the pad geometry shifted with the stroke)\n')
# stop rule at zeta 0.05
P('\n## Stop-rule check (zeta 0.05): reserve >= 2 mm, tilt <= 3.0 deg, n <= 12 g\n')
stop = {}
for model in ('items', 'cad', 'cad_E'):
    ok = [k for k in S if k[0] == model and abs(k[3] - 0.05) < 1e-9 and S[k]['reserve'] >= 2 and S[k]['tilt'] <= 3.0 and S[k]['n'] <= 12]
    stop[model] = len(ok); P('- %s: %d of %d grid points (incl. the baseline pad) meet the three limits at zeta 0.05' % (model, len(ok), len([k for k in S if k[0] == model and abs(k[3] - 0.05) < 1e-9])))
P('\n**Stop rule %s** (a grid point exists for every model: %s).\n' % ('NOT triggered' if all(v > 0 for v in stop.values()) else 'TRIGGERED', stop))
# robust choice on CAD mass: tier 1 = feasible at all three zeta, tier 2 = feasible at zeta 0.02 and 0.05 (zeta 0.10 then reported, not met)
def feasible(zs):
    out = []
    for k in S:
        if k[0] != 'cad' or abs(k[2] - 0.020) < 1e-9 or abs(k[3] - zs[0]) > 1e-9: continue
        fp, sm = k[1], k[2]; ok = True; ex = []
        for z in zs:
            e = S[('cad', fp, sm, z)]; ex.append(e['Mexit'])
            if not (e['reserve'] >= 2 and e['tilt'] <= 3.0 and e['n'] <= 12 and e['reserve70'] >= 0): ok = False
        if ok: out.append(((fp, sm), max(ex), max(S[('cad', fp, sm, z)]['tilt'] for z in zs)))
    return sorted(out, key=lambda t: t[1])
P('\n## Pad point for the downstream steps (the zeta of the foam is unmeasured, D-222 LR-1)\n')
choice = None; tier = None
for tname, zs in (('all three zeta (0.02, 0.05, 0.10)', (0.02, 0.05, 0.10)), ('zeta 0.02 and 0.05 (0.10 not met)', (0.02, 0.05))):
    feas = feasible(zs)
    P('Feasible at %s on the CAD mass (reserve >= 2 mm, tilt <= 3.0 deg, n <= 12 g, drift-0.70 reserve >= 0): %d points' % (tname, len(feas)))
    for (fp, sm), ex, tl in feas: P('- %.0f N, %.0f mm: worst-zeta sleeve-exit moment %.2f N m, worst-zeta tilt %.2f deg' % (fp, sm * 1e3, ex, tl))
    if feas and choice is None:
        pref = [t for t in feas if t[2] <= 2.8] or feas; choice = pref[0][0]; tier = tname
        tilt_note = 'tilt <= 2.8 deg preferred and met' if [t for t in feas if t[2] <= 2.8] else 'NO point has tilt <= 2.8 deg (the audit s4.1 wish); the AR-008 limit 3.0 governs and the margin is thin'
if choice:
    P('\n**Chosen: Fp %.0f N, usable stroke %.0f mm** (tier: %s; smallest worst-zeta sleeve-exit moment; %s).' % (choice[0], choice[1] * 1e3, tier, tilt_note))
    xf, zf = pad_geom(choice[1])
    P('Pad geometry at the choice: x_foot %.4f m (baseline 0.3415), pad edge z %.4f m (baseline 0.195), A-P9 30.5 deg held; z extent +%.1f mm on each side vs baseline.' % (xf, zf + 0.006, (zf + 0.006 - 0.195) * 1e3))
    for z in (0.02, 0.05, 0.10):
        e = S[('cad', choice[0], choice[1], z)]; b = S[('cad', 30.0, 0.020, z)]; o = S[('items', 30.0, 0.020, 0.05)]
        P('- zeta %.2f: Mexit %.2f (cad baseline pad %.2f; old ITEMS baseline pad zeta 0.05 %.2f), Mz_arm %.2f, tilt %.2f, n %.2f, reserve %.1f mm, drift-0.70 reserve %.1f mm  %s' % (z, e['Mexit'], b['Mexit'], o['Mexit'], e['Mz_arm'], e['tilt'], e['n'], e['reserve'], e['reserve70'], '' if (e['reserve'] >= 2 and e['tilt'] <= 3.0 and e['n'] <= 12) else '<-- limit not met'))
    # zeta at which n reaches 12 g (linear in zeta between 0.05 and 0.10, EST)
    e5, e10 = S[('cad', choice[0], choice[1], 0.05)], S[('cad', choice[0], choice[1], 0.10)]
    if e10['n'] > 12: P('n = 12 g (A-P5) is reached at zeta about %.3f (linear between the 0.05 and 0.10 rows, EST): the pad specification must require a measured equivalent zeta below this.' % (0.05 + 0.05 * (12 - e5['n']) / (e10['n'] - e5['n'])))
open(os.path.join(HERE, 'step2_table.md'), 'w').write('\n'.join(L) + '\n')
json.dump(dict(choice=dict(Fp=choice[0], s_max=choice[1]) if choice else None, stop=stop, tier=tier,
               summary={'%s|%g|%g|%g' % k: v for k, v in S.items()}), open(os.path.join(HERE, 'step2_choice.json'), 'w'), indent=1, default=float)
print('\n'.join(L[-25:]))
