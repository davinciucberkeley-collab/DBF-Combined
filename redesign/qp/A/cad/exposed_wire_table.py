"""exposed_wire_table.py - per-wire exposed-length table for concept A, generated from out/wire_inventory.json (T-099 F-9).

    python -I redesign/qp/A/cad/exposed_wire_table.py     -> prints the table and writes out/EXPOSED-WIRING.md

Category: interference / geometry bookkeeping (polyline lengths of the CAD strand centre lines, classified per 1 mm sample by
wire_inventory.py; sharp-corner lengths, the drawn fillets are 1-3 % shorter). Exposed = outside the arm tubes, conduits,
foam grooves and the bay cover AVN-008. The reasons are the D-199.2 reasons (redesign/review/QP-5/HARNESS-ENCLOSED.md) re-read
against the D-240 CAD; a "-" reason means the wire has no exposed run beyond joint samples.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "out", "wire_inventory.json")
OUT = os.path.join(HERE, "out", "EXPOSED-WIRING.md")

NAME = {
    "E-HRN-01": ("XT60 mating link (connector pair)", "connector body, 3 mm; the XT60 pair is a field-disconnect item (D-199.2 #9)"),
    "E-HRN-02": ("Phase leads, motor UR to ESC", "joint samples only where the bundle leaves a conduit / the raceway / the cover notch (D-199.2 #1)"),
    "E-HRN-03": ("Phase leads, motor UL to ESC", "same as E-HRN-02"),
    "E-HRN-04": ("Phase leads, motor LR to ESC", "same as E-HRN-02"),
    "E-HRN-05": ("Phase leads, motor LL to ESC", "same as E-HRN-02"),
    "E-HRN-06": ("ESC signal ribbon, ESC to FC", "-"),
    "E-HRN-07": ("Servo lead R, FC pad S5 to servo", "last run from the groove to the servo boot: the servo pocket stays open for the +-20 deg arm sweep (D-199.2 #8)"),
    "E-HRN-08": ("Servo lead L, FC pad S6 to servo", "same as E-HRN-07"),
    "E-HRN-09": ("RX CRSF / UART lead", "-  (enclosed under the bay cover and the RX hood; D-199.2 #5 counted the notch exit, the D-240 routing has no exposed run)"),
    "E-HRN-10": ("GPS lead", "leaves the plug inboard through a low bottom-open slot (D-199.2 #7)"),
    "E-HRN-11": ("Airspeed I2C lead, FC to MS4525 board", "-  (cover, window drop and core groove)"),
    "E-HRN-12": ("Battery tail, XT60 female to ESC BAT pads (14 AWG)", "the XT60 pair must stay outboard of the pack end (field disconnect); the tail lies on the plate and enters the cover through a bottom-open slot (D-199.2 #2)"),
    "E-HRN-13": ("Vendor pack power leads (2 x 14 AWG), pack face to XT60 male", "vendor leads, taped to the skin; not ours to bury (D-199.2 #3)"),
    "E-HRN-14": ("Pack balance lead", "vendor lead, taped to the skin (D-199.2 #4)"),
}


def main():
    d = json.load(open(SRC, encoding="utf-8"))
    rows = []
    tot = 0.0
    for r in d["rows"]:
        e = r["edge"]
        nm, why = NAME.get(e, (e, "—"))
        ex = r["strands"] * r["exposed_m"]
        tot += ex
        rows.append((e, nm, r["strands"], r["exposed_m"], ex, r["total_m"], why))
    lines = [
        "# Concept A exposed wiring, per wire (generated)",
        "",
        "Generated by `redesign/qp/A/cad/exposed_wire_table.py` from `redesign/qp/A/cad/out/wire_inventory.json` (CAD of D-240, "
        "2026-11-23). Category: geometry bookkeeping (polyline centre-line lengths classified per 1 mm sample; sharp corners, drawn "
        "fillets are 1-3 % shorter). Rule: root `CLAUDE.md` (user 2026-11-15): route wires inside tubes, cores, fairings or covers; list "
        "what stays exposed with length and reason, minimum.",
        "",
        "| Wire | Name | Strands | Exposed per strand (m) | Exposed, strand-m | Total path per strand (m) | Reason it is not enclosed |",
        "|---|---|---|---|---|---|---|",
    ]
    for e, nm, n, ex1, ex, tp, why in rows:
        lines.append("| %s | %s | %d | %.4f | %.3f | %.4f | %s |" % (e, nm, n, ex1, ex, tp, why))
    lines += ["", "**Total exposed: %.3f strand-metres** (`totals_strand_m.EXPOSED` = %.4f in the JSON). Enclosed: arm %.3f, raceway %.3f, "
              "groove %.3f, cover %.3f strand-m." % (tot, d["totals_strand_m"]["EXPOSED"], d["totals_strand_m"]["ARM"], d["totals_strand_m"]["RACE"],
                                                       d["totals_strand_m"]["GROOVE"], d["totals_strand_m"]["COVER"]),
              "",
              "Pitot: the pitot lines AVN-009-T / AVN-009-S are drawn (E3d, 39 mm each); they are tubes, not wires, and are not in this table.",
              "Earlier counts (9.09, 4.27 strand-m at D-198; 0.87 at D-199; 1.02 quoted in the Explorer) are superseded by this table.",
              ""]
    txt = "\n".join(lines)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8", newline="\n").write(txt)
    print(txt)


if __name__ == "__main__":
    main()
