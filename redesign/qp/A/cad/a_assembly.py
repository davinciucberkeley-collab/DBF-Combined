"""a_assembly.py - build-sequence check for concept A: support, swept insertion paths, wire order.
    python -I redesign/qp/A/cad/a_assembly.py     -> out/ASSEMBLY.md, out/assembly.json (runs Blender in the background, no render)
Uses the collision job of collide_a.py (written here with --job-only)."""
import json
import os
import subprocess
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import a_model as m                 # noqa: E402
import a_assembly_plan as ap        # noqa: E402

OUT = os.path.join(HERE, 'out')
BLENDER = os.environ.get('BLENDER', 'C:/Users/dillo/tools/blender/blender-4.5.14-windows-x64/blender.exe')


def main():
    subprocess.run([sys.executable, '-I', os.path.join(HERE, 'collide_a.py'), '--job-only', '--no-sweep'], check=True)
    upto = os.environ.get('A_UPTO')
    if upto:
        ids = [s[0] for s in ap.STEPS]
        ap.STEPS = ap.STEPS[:ids.index(upto) + 1]
    bench = set(getattr(ap, 'BENCH', ()))
    mk = lambda s: dict(id=s[0], caption=s[1], parts=s[2], dir=s[3], travel=s[4], step=s[5] or 1)
    plan = [mk(s) for s in ap.STEPS if s[2] and s[0] not in bench]                  # main run: the wing and everything on it (marker steps carry wires only)
    plan_bench = [mk(s) for s in ap.STEPS if s[2] and s[0] in bench]                # D-202 bench run: the cage frame built away from the wing (nothing else placed)
    json.dump(plan, open(os.path.join(OUT, '_plan.json'), 'w'))
    json.dump(plan_bench, open(os.path.join(OUT, '_plan_bench.json'), 'w'))

    def run_blender(pl, rp, log):
        if os.path.exists(rp):
            os.remove(rp)
        p = subprocess.run([BLENDER, '-b', '--factory-startup', '--python-exit-code', '1', '-P',
                            os.path.join(HERE, 'a_assembly_blender.py'), '--', os.path.join(OUT, '_job.json'), pl, rp], capture_output=True, text=True)
        open(os.path.join(OUT, log), 'w').write(p.stdout + p.stderr)
        if not os.path.exists(rp):
            sys.exit('Blender failed; see out/%s' % log)
        return {r['id']: r for r in json.load(open(rp))['steps']}

    res = run_blender(os.path.join(OUT, '_plan.json'), os.path.join(OUT, 'assembly.json'), 'assembly.log')
    if plan_bench:
        res.update(run_blender(os.path.join(OUT, '_plan_bench.json'), os.path.join(OUT, 'assembly_bench.json'), 'assembly_bench.log'))
    res.update({s[0]: dict(id=s[0], worst_mm=0.0, pairs=[]) for s in ap.STEPS if not s[2]})
    placed, rows, bad = set(), [], 0
    mech = [e for e in m.EDGES if e['id'] not in m.ELEC and e['via'] != 'CT-TIE']
    for i, s in enumerate(ap.STEPS):
        sid, cap, parts = s[0], s[1], s[2]
        sup = []
        for pid in parts:
            ok = i == 0 or sid == getattr(ap, 'BENCH_START', None) or any((e['part_a'] == pid and (e['part_b'] in placed or e['part_b'] in parts)) or
                               (e['part_b'] == pid and (e['part_a'] in placed or e['part_a'] in parts)) for e in mech)
            if not ok:
                sup.append(pid)
        r = res[sid]
        blocked = r['worst_mm'] > 0.05
        bad += bool(blocked) + bool(sup)
        rows.append((sid, cap, len(parts), 'BLOCKED' if blocked else 'ok', r['worst_mm'], r['pairs'][:3], sup))
        placed |= set(parts)
    allp = {k for k, p in m.PARTS.items() if not p.get('mass_proxy')}
    missing = sorted(allp - placed) if not upto else []
    # D-198 wire order: every electrical edge is laid exactly once, in a step after the steps that place both end parts; THREAD steps precede their partner
    idx = {s[0]: i for i, s in enumerate(ap.STEPS)}
    where = {}
    for i, s in enumerate(ap.STEPS):
        for e in (s[6] if len(s) > 6 else []):
            where.setdefault(e, []).append(i)
    first = {}
    for i, s in enumerate(ap.STEPS):
        for pid in s[2]:
            first.setdefault(pid, i)
    late = []
    for e in m.EDGES:
        if e['id'] not in m.ELEC:
            continue
        w = where.get(e['id'], [])
        if upto:
            continue
        if len(w) != 1:
            late.append('%s (laid %d times)' % (e['id'], len(w)))
        elif any(first.get(pid, 10 ** 6) >= w[0] for pid in (e['part_a'], e['part_b'])):
            late.append('%s (laid before both end parts are on)' % e['id'])
    for t, before in getattr(ap, 'THREAD_BEFORE', {}).items():
        if idx[t] >= idx[before]:
            late.append('thread step %s after %s' % (t, before))
    L = ['# Concept A build sequence check (generated by a_assembly.py)', '',
         '%d steps (%d of them swept in the D-202 bench run, the rest in the main run), %d parts placed of %d; steps with a blocked path or no support: %d; parts not in the sequence: %s; wires '
         'laid before both end parts are on: %s.' % (len(ap.STEPS), len(bench), len(placed), len(allp), bad, ', '.join(missing) or 'none',
                                                    ', '.join(late) or 'none'), '',
         '| Step | What | Parts | Path | Worst mm | Blocking pairs (depth mm at travel mm) | Unsupported |',
         '|---|---|---|---|---|---|---|']
    for sid, cap, n, st, w, pr, sup in rows:
        L.append('| %s | %s | %d | %s | %.2f | %s | %s |' % (
            sid, cap, n, st, w, '; '.join('%s x %s %.2f @%g' % (p['a'], p['b'], p['depth_mm'], p['at_t_mm']) for p in pr) or '-',
            ', '.join(sup) or '-'))
    open(os.path.join(OUT, 'ASSEMBLY-upto-%s.md' % upto if upto else 'ASSEMBLY.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print('\n'.join(L))
    return 1 if bad or missing or late else 0


if __name__ == '__main__':
    sys.exit(main())
