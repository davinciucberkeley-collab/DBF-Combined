"""a_assembly.py - build-sequence check for concept A: support, swept insertion paths, wire order.
    python -I redesign/qp/A/cad/a_assembly.py     -> out/ASSEMBLY.md, out/assembly.json (runs Blender in the background, no render)
Uses the collision job of collide_a.py (written here with --job-only)."""
import json
import os
import subprocess
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import a_model as m                 # noqa: E402
import a_assembly_plan as ap        # noqa: E402

OUT = os.path.join(HERE, 'out')
BLENDER = os.environ.get('BLENDER', 'C:/Users/dillo/tools/blender/blender-4.5.14-windows-x64/blender.exe')


def main():
    subprocess.run([sys.executable, '-I', os.path.join(HERE, 'collide_a.py'), '--job-only', '--no-sweep'], check=True)
    upto = os.environ.get('A_UPTO')
    if upto:
        ids = [s[0] for s in ap.STEPS]
        ap.STEPS = ap.STEPS[:ids.index(upto) + 1]
    plan = [dict(id=s[0], caption=s[1], parts=s[2], dir=s[3], travel=s[4], step=s[5] or 1) for s in ap.STEPS]
    json.dump(plan, open(os.path.join(OUT, '_plan.json'), 'w'))
    rp = os.path.join(OUT, 'assembly.json')
    if os.path.exists(rp):
        os.remove(rp)
    p = subprocess.run([BLENDER, '-b', '--factory-startup', '--python-exit-code', '1', '-P',
                        os.path.join(HERE, 'a_assembly_blender.py'), '--', os.path.join(OUT, '_job.json'),
                        os.path.join(OUT, '_plan.json'), rp], capture_output=True, text=True)
    open(os.path.join(OUT, 'assembly.log'), 'w').write(p.stdout + p.stderr)
    if not os.path.exists(rp):
        sys.exit('Blender failed; see out/assembly.log')
    res = {r['id']: r for r in json.load(open(rp))['steps']}
    placed, rows, bad = set(), [], 0
    mech = [e for e in m.EDGES if e['id'] not in m.ELEC and e['via'] != 'CT-TIE']
    for i, s in enumerate(ap.STEPS):
        sid, cap, parts = s[0], s[1], s[2]
        sup = []
        for pid in parts:
            ok = i == 0 or any((e['part_a'] == pid and (e['part_b'] in placed or e['part_b'] in parts)) or
                               (e['part_b'] == pid and (e['part_a'] in placed or e['part_a'] in parts)) for e in mech)
            if not ok:
                sup.append(pid)
        r = res[sid]
        blocked = r['worst_mm'] > 0.05
        bad += bool(blocked) + bool(sup)
        rows.append((sid, cap, len(parts), 'BLOCKED' if blocked else 'ok', r['worst_mm'], r['pairs'][:3], sup))
        placed |= set(parts)
    allp = {k for k, p in m.PARTS.items() if not p.get('mass_proxy')}
    missing = sorted(allp - placed) if not upto else []
    late = [e['id'] for e in m.EDGES if e['id'] in m.ELEC and not upto and not (e['part_a'] in placed and e['part_b'] in placed)]
    L = ['# Concept A build sequence check (generated by a_assembly.py)', '',
         '%d steps, %d parts placed of %d; steps with a blocked path or no support: %d; parts not in the sequence: %s; wires '
         'laid before both end parts are on: %s.' % (len(ap.STEPS), len(placed), len(allp), bad, ', '.join(missing) or 'none',
                                                    ', '.join(late) or 'none'), '',
         '| Step | What | Parts | Path | Worst mm | Blocking pairs (depth mm at travel mm) | Unsupported |',
         '|---|---|---|---|---|---|---|']
    for sid, cap, n, st, w, pr, sup in rows:
        L.append('| %s | %s | %d | %s | %.2f | %s | %s |' % (
            sid, cap, n, st, w, '; '.join('%s x %s %.2f @%g' % (p['a'], p['b'], p['depth_mm'], p['at_t_mm']) for p in pr) or '-',
            ', '.join(sup) or '-'))
    open(os.path.join(OUT, 'ASSEMBLY-upto-%s.md' % upto if upto else 'ASSEMBLY.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print('\n'.join(L))
    return 1 if bad or missing or late else 0


if __name__ == '__main__':
    sys.exit(main())
