"""a_model.py - FACADE for the concept A CAD model (scaled quad tailsitter, D-182) on the K09-L framework (fusionkit / k09kit, unmodified).

The model is split by lane into the package amodel/ (refactor only, no geometry change):
    amodel/common.py      shared constants, frames, airfoil helpers, P/E/WIRE registries (changes need coordination)
    amodel/wing.py        LANE A: wing core/section, spar, elevons, balance, caps/stops, damper, fins, hub, arms, cups, struts, pack tray
    amodel/propulsion.py  LANE B: motors, props, ESC, prop/motor hardware joints
    amodel/electrical.py  LANE C: pack, avionics, servos/linkage, landing feet, harness, hardware lumps, joint/contact pass
This file re-exports every name (public and underscored) so importers (`import a_model as m`; m.PARTS, m.build_wing, ...) are unchanged.
PARTS / EDGES are ordered tables: amodel/__init__.py imports wing, propulsion, electrical in that order, as the old single file did.
model/<sub>/fusion/<sub>.py are 6-line stubs that call build_<sub>(ctx). model/<sub>/interfaces.json is GENERATED by gen_interfaces.py.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)
import amodel  # noqa: E402,F401  (registers PARTS / EDGES in lane order)
from amodel import common, wing, propulsion, electrical  # noqa: E402

for _mod in (common, wing, propulsion, electrical):
    for _k, _v in vars(_mod).items():
        if not (_k.startswith('__') and _k.endswith('__')):
            globals()[_k] = _v
del _mod, _k, _v
