def hm(minutes):
    h, mm = divmod(int(round(minutes)), 60)
    return ('%d h %02d min' % (h, mm)) if h else '%d min' % mm


def key_of(pid):
    return re.sub(r'-(UR|UL|LR|LL|RU|RL|LU|[RLC])$', '', pid)


def clean_name(n):
    n = re.sub(r'\s*\((UR|UL|LR|LL|R|L)[,;)][^)]*\)?', '', n)
    n = re.sub(r'\s*\((UR|UL|LR|LL|R|L)\)', '', n)
    return n.split(' (')[0].split(';')[0].strip()


def bom_for(pid):
    mp = next((x for x in pl.MAP if pid.startswith(x[0])), None)
    if not mp:
        return '-'
    return ', '.join('%s %s' % (b, BOM[b]['ship_group']) for b in mp[2] if b in BOM)


def parts_table(step_id):
    ids = list(PLAN[step_id][2])
    groups = {}
    for pid in ids:
        groups.setdefault(key_of(pid), []).append(pid)
    rows = []
    for k, pp in groups.items():
        p0 = m.PARTS[pp[0]]
        mass = sum(m.PARTS[x]['mass_g'] for x in pp)
        rows.append('| `%s` x%d | %s | %s | %s | %.1f |' % (k if len(pp) > 1 else pp[0], len(pp), clean_name(p0['name']),
                                                     'made' if p0['make_or_buy'] == 'make' else 'bought', bom_for(pp[0]), mass))
    return rows, sum(m.PARTS[x]['mass_g'] for x in ids)


def stage_of(step_id):
    for si, (t, ids) in enumerate(STAGES):
        if step_id in ids:
            return si
    return None


